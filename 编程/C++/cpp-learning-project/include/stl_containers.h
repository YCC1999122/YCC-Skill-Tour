#ifndef STL_CONTAINERS_H
#define STL_CONTAINERS_H
#pragma once

#include <vector>      // 动态数组容器
#include <list>        // 双向链表容器
#include <deque>       // 双端队列容器
#include <array>       // 固定大小数组容器
#include <map>         // 有序关联映射（红黑树实现）
#include <unordered_map> // 无序关联映射（哈希表实现）
#include <set>         // 有序集合
#include <unordered_set> // 无序集合
#include <string>      // 字符串类
#include <algorithm>   // STL算法库

// ============================================================================
// 命名空间 stl_demo
// 作用: 将STL相关的演示函数封装在独立的命名空间中
// 注意: 不使用 stl 作为命名空间名，避免与标准库产生混淆
// ============================================================================
namespace stl_demo {

// ----------------------------------------------------------------------------
// 函数: demo_sequence_containers
// 描述: 演示顺序容器：vector, list, deque, array
// 内容:
//   - vector: 动态数组，连续内存，随机访问O(1)，中间插入O(n)
//   - list: 双向链表，非连续内存，任意位置插入O(1)，不支持随机访问
//   - deque: 双端队列，双端插入删除O(1)，随机访问O(1)（比vector稍慢）
//   - array: 固定大小数组，封装C风格数组，大小在编译时确定
// ----------------------------------------------------------------------------
void demo_sequence_containers();

// ----------------------------------------------------------------------------
// 函数: demo_associative_containers
// 描述: 演示关联容器：map, unordered_map, set, unordered_set
// 内容:
//   - map: 键值对，有序，基于红黑树，查找O(log n)
//   - unordered_map: 键值对，无序，基于哈希表，查找平均O(1)
//   - set: 集合（只有键），有序，基于红黑树
//   - unordered_set: 集合，无序，基于哈希表
// ----------------------------------------------------------------------------
void demo_associative_containers();

// ----------------------------------------------------------------------------
// 函数: demo_string_operations
// 描述: 演示string类的常用操作
// 内容: 字符串拼接、查找、替换、截取、比较、转换等
// ----------------------------------------------------------------------------
void demo_string_operations();

// ----------------------------------------------------------------------------
// 函数: demo_iterators
// 描述: 演示迭代器的使用和迭代器失效问题
// 内容:
//   - 迭代器的基本用法（begin/end, 前缀/后缀递增）
//   - 迭代器分类（输入/输出/前向/双向/随机访问）
//   - 迭代器失效场景及避免方法
// ----------------------------------------------------------------------------
void demo_iterators();

// ----------------------------------------------------------------------------
// 函数: demo_algorithms
// 描述: 演示常用STL算法
// 内容:
//   - sort: 排序
//   - find/find_if: 查找
//   - copy: 复制
//   - transform: 变换
//   - for_each: 遍历
//   - accumulate: 累加（需要<numeric>）
//   - remove/remove_if: 移除
//   - reverse: 反转
// ----------------------------------------------------------------------------
void demo_algorithms();

// ----------------------------------------------------------------------------
// 函数: run_stl_demo
// 描述: 运行所有STL演示（统一入口函数）
// ----------------------------------------------------------------------------
void run_stl_demo();

} // namespace stl_demo

#endif // STL_CONTAINERS_H

/**
 * ============================================================
 * Animal 接口：动物行为的规范
 *
 * 【接口（interface）是什么】
 * - 接口是一种特殊的抽象类型，是一组方法的集合（契约/规范）
 * - 接口定义了"能做什么"，但不定义"怎么做"
 * - 类通过implements关键字实现接口，必须实现接口中所有的抽象方法
 * - Java中类可以实现多个接口（弥补了单继承的不足）
 * - 接口不能被实例化，也没有构造方法
 *
 * 【接口 vs 抽象类】
 * - 抽象类：is-a关系，"是一种"，有继承关系，单继承
 * - 接口：has-a关系，"具备某种能力"，行为规范，多实现
 * - 抽象类可以有成员变量、构造方法、普通方法
 * - 接口中（Java 8之前）只能有抽象方法和静态常量
 *
 * 【Java 8+ 接口的新特性】
 * - 默认方法（default method）：接口中可以有带实现的方法
 * - 静态方法（static method）：接口中可以有静态方法
 * - 这些新特性让接口的功能更强大，但也带来了一些设计上的考量
 *
 * 【接口中成员的特点（Java 8+）】
 * - 成员变量：默认是 public static final 的（必须初始化）
 * - 抽象方法：默认是 public abstract 的
 * - 默认方法：用default修饰，有方法体，子类继承（可重写）
 * - 静态方法：用static修饰，有方法体，只能通过接口名调用
 * ============================================================
 */
public interface Animal {

    /**
     * 接口中的常量：默认就是 public static final 的
     * 可以省略这些修饰符，编译器会自动加上
     * 这里定义动物的分类（用于演示常量）
     */
    String TYPE_MAMMAL = "哺乳动物";     // 省略了 public static final
    String TYPE_BIRD = "鸟类";
    String TYPE_FISH = "鱼类";

    /**
     * 抽象方法：吃东西
     * 接口中的方法默认是 public abstract 的
     * 实现类必须实现这个方法
     */
    void eat();

    /**
     * 抽象方法：发出声音
     */
    void makeSound();

    /**
     * 默认方法：睡觉（Java 8+ 新特性）
     *
     * 【默认方法（default method）】
     * - 用default关键字修饰，有方法体
     * - 实现类可以直接继承使用，也可以重写
     * - 主要用途：接口升级时，给已有方法增加新功能，不破坏现有实现
     * - 注意：如果一个类实现了多个接口，且这些接口有相同的默认方法，
     *   那么该类必须重写这个方法来解决冲突
     */
    default void sleep() {
        System.out.println("动物在睡觉...");
    }

    /**
     * 默认方法：介绍自己
     * 默认方法可以调用接口中的其他方法（包括抽象方法）
     */
    default void introduce() {
        System.out.println("我是一只动物，我会吃东西和发出声音。");
        eat();
        makeSound();
    }

    /**
     * 静态方法：获取动物分类信息（Java 8+ 新特性）
     *
     * 【接口静态方法】
     * - 用static关键字修饰，有方法体
     * - 只能通过接口名调用，不能通过实现类对象调用
     * - 主要用途：提供和接口相关的工具方法
     */
    static void printAnimalTypes() {
        System.out.println("动物分类: " + TYPE_MAMMAL + "、" + TYPE_BIRD + "、" + TYPE_FISH);
    }
}

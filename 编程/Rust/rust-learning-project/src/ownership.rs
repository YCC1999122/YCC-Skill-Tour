// ============================================================
// ownership.rs - 所有权与借用模块
// ============================================================
// 所有权（Ownership）是Rust最核心、最独特的特性
// 它使得Rust能够在没有垃圾回收器（GC）的情况下保证内存安全
//
// 所有权规则（三条黄金法则）：
//   1. Rust中的每个值都有一个所有者（owner）变量
//   2. 同一时间只能有一个所有者
//   3. 当所有者离开作用域时，这个值将被丢弃（drop）
//
// 借用（Borrowing）：
//   - 通过引用（&）来使用值，但不获取所有权
//   - 借用规则：
//     a. 同一时间，只能有一个可变引用，或任意数量的不可变引用
//     b. 引用必须总是有效的（不能有悬垂引用）
//
// 生命周期（Lifetime）：
//   - 引用的有效范围
//   - 大多数情况下，编译器可以自动推导
//   - 复杂情况下需要手动标注生命周期参数
// ============================================================


<?php
// ============================================================
// Person 类 - 面向对象基础示例
// ============================================================
// 演示类的定义、属性、方法、构造函数、析构函数、访问控制等
// ============================================================

namespace App\Oop;

/**
 * Person 类 - 人类
 * 
 * 演示以下 OOP 概念：
 * - 类与对象
 * - 属性（成员变量）
 * - 方法（成员函数）
 * - $this 关键字
 * - 构造函数 __construct
 * - 析构函数 __destruct
 * - 访问控制（public/protected/private）
 * - 类型属性（PHP 7.4+）
 * - 类常量
 */
class Person
{
    // ============================================================
    // 类常量
    // ============================================================
    // 使用 const 关键字定义类常量
    // 类常量属于类本身，不属于某个对象
    // 访问方式：Person::SPECIES 或 self::SPECIES
    public const SPECIES = '智人';

    // ============================================================
    // 静态属性
    // ============================================================
    // 使用 static 关键字定义静态属性
    // 静态属性属于类本身，所有对象共享同一份
    // 常用于统计创建了多少个对象
    public static int $count = 0;

    // ============================================================
    // 属性（成员变量）
    // ============================================================
    // 访问控制修饰符：
    // - public:    公开的，任何地方都可以访问
    // - protected: 受保护的，只有本类和子类可以访问
    // - private:   私有的，只有本类可以访问

    // 类型属性（PHP 7.4+ 支持类型声明）
    public string $name;      // 姓名 - 公开的，外部可直接访问
    protected int $age;       // 年龄 - 受保护的，子类可访问
    private string $idCard;   // 身份证号 - 私有的，只有本类可访问

    // ============================================================
    // 构造函数 __construct
    // ============================================================
    // 创建对象时自动调用
    // 用于初始化对象属性
    // PHP 7.4+ 支持构造函数属性提升（在参数列表中直接声明属性）
    /**
     * 构造函数
     * 
     * @param string $name 姓名
     * @param int $age 年龄
     * @param string $idCard 身份证号
     */
    public function __construct(string $name, int $age, string $idCard)
    {
        // $this 关键字指向当前对象实例
        // 用于访问对象的属性和方法
        $this->name = $name;          // 给公开属性赋值
        $this->age = $age;            // 给受保护属性赋值
        $this->idCard = $idCard;      // 给私有属性赋值

        // 静态属性使用 self:: 访问（指向当前类）
        self::$count++;  // 每创建一个对象，计数器加 1
        echo "  [构造] Person 对象创建：{$this->name}\n";
    }

    // ============================================================
    // 析构函数 __destruct
    // ============================================================
    // 对象销毁时自动调用
    // 常用于释放资源（关闭文件、数据库连接等）
    /**
     * 析构函数
     */
    public function __destruct()
    {
        echo "  [析构] Person 对象销毁：{$this->name}\n";
    }

    // ============================================================
    // 公开方法（public）
    // ============================================================
    /**
     * 说话方法 - 公开的，外部可以调用
     * 
     * @param string $message 要说的话
     * @return string
     */
    public function say(string $message): string
    {
        return "{$this->name}说：{$message}";
    }

    /**
     * 获取年龄（因为 age 是 protected，外部不能直接访问）
     * 
     * @return int
     */
    public function getAge(): int
    {
        return $this->age;
    }

    /**
     * 设置年龄
     * 
     * @param int $age
     */
    public function setAge(int $age): void
    {
        // 可以在 setter 中添加验证逻辑
        if ($age >= 0 && $age <= 150) {
            $this->age = $age;
        }
    }

    // ============================================================
    // 受保护方法（protected）
    // ============================================================
    /**
     * 受保护的方法 - 只有本类和子类可以调用
     */
    protected function protectedMethod(): string
    {
        return '这是受保护的方法';
    }

    // ============================================================
    // 私有方法（private）
    // ============================================================
    /**
     * 私有方法 - 只有本类可以调用
     */
    private function privateMethod(): string
    {
        return '这是私有方法，只有 Person 类内部可以调用';
    }

    /**
     * 公开方法调用私有方法
     */
    public function callPrivateMethod(): string
    {
        return $this->privateMethod();
    }

    // ============================================================
    // 静态方法
    // ============================================================
    /**
     * 静态方法 - 属于类本身，不需要实例化就能调用
     * 
     * @return int 已创建的 Person 对象总数
     */
    public static function getCount(): int
    {
        // 静态方法中不能使用 $this
        return self::$count;
    }
}

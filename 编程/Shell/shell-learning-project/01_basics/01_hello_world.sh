# -------------------- 1. shebang 行说明 --------------------
# 脚本的第一行 #!/bin/bash 叫做 shebang（释伴行）
# #! 是特殊标记，告诉系统这个脚本需要用 /bin/bash 解释器来执行
# 如果脚本是用 sh 编写的，可以写成 #!/bin/sh
# 注意：shebang 必须是文件的第一行，前面不能有任何字符（包括空格和空行）

# -------------------- 2. echo 输出命令 --------------------
# echo 是最常用的输出命令，用于在屏幕上打印文本
echo "========== 1. echo 输出演示 =========="

# 直接输出字符串
echo "Hello, World!"            # 输出：Hello, World!

# echo 不加引号也可以输出简单文本（不推荐，遇到特殊字符会出问题）
echo Hello World                 # 输出：Hello World

# 使用 -e 选项可以启用转义字符（如 \n 换行、\t 制表符等）
echo -e "第一行\n第二行\t第三行"   # -e 让 \n 和 \t 生效

# 使用 -n 选项可以不输出末尾的换行符
echo -n "当前日期是："
date                             # date 命令的输出会紧跟在上面的文字后面

echo ""                          # 输出一个空行，用于分隔

# -------------------- 3. 注释 --------------------
# 这是单行注释，以 # 开头，整行都会被 bash 忽略
# 注释用于解释代码的作用、作者、版本等信息
# 好的注释能让代码更易读、易维护

: '
这是多行注释的写法（不常用，了解即可）
使用 : 命令配合单引号块可以实现多行注释
: 是一个空命令，什么也不做
单引号内的所有内容都会被当作字符串参数
注意：单引号必须单独占一行
'

echo ""
echo "========== 2. 变量定义与使用 =========="

# -------------------- 4. 变量定义与使用 --------------------
# Bash 中定义变量非常简单，格式：变量名=值
# 注意：等号两边不能有空格！这是很多初学者容易犯的错误

# 定义一个字符串变量
name="张三"                       # 变量名 name，值为 "张三"

# 使用变量时，需要在变量名前加 $ 符号
echo "我的名字是：$name"           # 输出：我的名字是：张三

# 也可以用 ${变量名} 的形式，更清晰，也能避免歧义
echo "我的名字是：${name}"         # 输出：我的名字是：张三

# 定义数字变量（Bash 中变量本质都是字符串，但可以参与数值运算）
age=25
echo "年龄：$age 岁"

# 变量名的命名规则：
# - 只能由字母、数字、下划线组成
# - 第一个字符必须是字母或下划线（不能是数字）
# - 区分大小写（Name 和 name 是不同的变量）
# - 不能使用 bash 的关键字（如 if、for、while 等）
_user_name="李四"                 # 以下划线开头，合法
_123="测试"                       # 以下划线开头后接数字，合法
echo "用户：$_user_name"

# 变量重新赋值
name="王五"                       # 直接用新值覆盖旧值
echo "更新后的名字：$name"

echo ""
echo "========== 3. 引号区别 =========="

# -------------------- 5. 引号区别（单引号/双引号/反引号） --------------------
# Bash 中有三种引号，各有不同的作用

# --- 双引号 " " ---
# 双引号内的内容：
# - $ 变量会被解析（替换为变量的值）
# - 反引号命令会被执行
# - 转义字符（如 \n）需要配合 echo -e 才生效
# - 空格和特殊字符会被当作普通字符保留
city="北京"
echo "双引号：我住在$city"         # 变量会被解析，输出：双引号：我住在北京

# --- 单引号 ' ' ---
# 单引号内的内容：
# - 所有字符都原样输出，不做任何解析
# - $ 变量、反引号、转义符都失效
# - 单引号内不能再出现单引号（即使转义也不行）
echo '单引号：我住在$city'         # 变量不会被解析，输出：单引号：我住在$city

# --- 反引号 ` `（旧写法，不推荐） ---
# 反引号用于命令替换，即把命令的输出结果作为值
# 现代 bash 推荐使用 $() 代替反引号（见第7节）
current_date=`date`                # 执行 date 命令，把结果赋给 current_date
echo "反引号获取日期：$current_date"

# 对比三种引号的效果
echo ""
echo "--- 三种引号对比 ---"
echo "双引号：name=$name"          # 变量被解析
echo '单引号：name=$name'          # 变量不解析
echo "反引号：今天是 `date +%Y-%m-%d`"  # 命令被执行

echo ""
echo "========== 4. 读取用户输入 read =========="

# -------------------- 6. 读取用户输入 read --------------------
# read 命令用于从标准输入（键盘）读取用户输入
# 格式：read 变量名
# 注意：本脚本是自动演示，为了不阻塞，我们用变量模拟输入
# 实际使用时，取消下面几行的注释即可交互

# echo -n "请输入你的名字："
# read user_name                    # 等待用户输入，输入的内容存入 user_name 变量
# echo "你好，$user_name！"

# read 的常用选项：
# -p 提示信息：直接在 read 命令中显示提示
# -s 静默模式：输入时不显示字符（常用于密码输入）
# -t 秒数：设置超时时间，超时后 read 自动退出
# -n 字符数：读取指定数量的字符后自动结束

# 使用 -p 选项（提示信息）
# read -p "请输入你的年龄：" user_age
# echo "你的年龄是 $user_age 岁"

# 使用 -s 选项（静默输入，比如密码）
# read -s -p "请输入密码：" password
# echo ""                           # 换行
# echo "密码已接收（长度：${#password}）"

# 为了演示不中断，这里直接输出说明
echo "read 命令用于读取用户键盘输入"
echo "常用选项：-p（提示） -s（静默） -t（超时） -n（字符数）"
echo "示例：read -p \"请输入名字：\" my_name"

echo ""
echo "========== 5. 命令替换 =========="

# -------------------- 7. 命令替换（$() / ``） --------------------
# 命令替换就是把一个命令的输出结果保存到变量中，或者嵌入到字符串中
# 有两种写法：$() 和 反引号 ``
# 推荐使用 $()，因为：
# 1. 可读性更好
# 2. 可以嵌套使用
# 3. 反引号在某些字体中不容易区分

# 写法一：$() 语法（推荐）
today=$(date +%Y-%m-%d)            # 执行 date +%Y-%m-%d，结果赋给 today
echo "今天的日期是：$today"

# 写法二：反引号语法（旧写法，兼容）
now_time=`date +%H:%M:%S`
echo "当前时间是：$now_time"

# 命令替换可以嵌套（$() 支持嵌套，反引号不支持）
# 例如：获取当前目录下的文件数量
file_count=$(ls | wc -l)           # ls 列出文件，wc -l 统计行数
echo "当前目录下的文件/目录数量：$file_count"

# 命令替换的结果可以直接参与字符串拼接
echo "当前系统：$(uname -s)，内核版本：$(uname -r)"

echo ""
echo "========== 6. 环境变量与全局变量 =========="

# -------------------- 8. 环境变量与全局变量 --------------------

# --- 环境变量 ---
# 环境变量是操作系统或 shell 预先定义好的变量，通常大写
# 环境变量在所有子进程中都可以访问
# 常用的环境变量：

echo "HOME（用户主目录）：$HOME"
echo "PATH（命令搜索路径）：$PATH"
echo "USER（当前用户名）：$USER"
echo "SHELL（当前shell）：$SHELL"
echo "PWD（当前工作目录）：$PWD"
echo "LANG（语言环境）：$LANG"
echo "HOSTNAME（主机名）：$HOSTNAME"

# 查看所有环境变量可以用 env 或 printenv 命令
# 本脚本只展示几个常用的

# --- 全局变量 ---
# 在脚本中直接定义的变量默认是全局变量
# 全局变量在整个脚本中都可以访问
global_var="我是全局变量"
echo "全局变量：$global_var"

# 使用 export 可以把变量导出为环境变量
# 这样子进程也能访问这个变量
export MY_VAR="导出的环境变量"
echo "已导出环境变量 MY_VAR：$MY_VAR"

echo ""
echo "========== 7. 特殊变量 =========="

# -------------------- 9. 特殊变量 --------------------
# Bash 中有一些特殊的变量，以 $ 开头，用于获取脚本或命令的相关信息

# --- $0 ---
# 当前脚本的文件名（包含路径，取决于调用方式）
echo "脚本文件名(\$0)：$0"

# --- $1, $2, $3 ... ---
# 脚本或函数的第1、2、3...个参数
# 本脚本如果直接运行没有参数，可以这样测试：
# ./01_hello_world.sh 参数1 参数2 参数3
echo "第一个参数(\$1)：${1:-无参数}"   # ${1:-无参数} 表示如果$1为空则显示"无参数"
echo "第二个参数(\$2)：${2:-无参数}"
echo "第三个参数(\$3)：${3:-无参数}"

# --- $# ---
# 传递给脚本或函数的参数个数
echo "参数个数(\$#)：$#"

# --- $@ ---
# 所有参数的列表，每个参数都是独立的字符串
# 用 "$@" 可以正确处理包含空格的参数
echo "所有参数(\$@)：$@"

# --- $* ---
# 所有参数的列表，用第一个字符（IFS的第一个字符，通常是空格）连接成一个字符串
# 用 "$*" 会把所有参数合并成一个字符串
echo "所有参数(\$*)：$*"

# $@ 和 $* 的区别在加双引号时才明显：
# "$@" → "$1" "$2" "$3" （每个参数独立）
# "$*" → "$1 $2 $3" （合并成一个字符串）
echo ""
echo "--- \$@ 和 \$* 的区别（用 for 循环演示）---"
echo "遍历 \$@："
for arg in "$@"; do
    echo "  参数：[$arg]"
done
echo "遍历 \$*："
for arg in "$*"; do
    echo "  参数：[$arg]"
done

# --- $? ---
# 上一个命令的退出状态码（返回值）
# 0 表示成功，非 0 表示失败
echo ""
ls /tmp > /dev/null 2>&1           # 执行一个命令，输出重定向到空设备
echo "上一条命令的退出码(\$?)：$?"

# --- $$ ---
# 当前 shell 进程的 PID（进程号）
echo "当前进程PID(\$\$)：$$"

# --- $! ---
# 最后一个后台运行进程的 PID
# 例如：sleep 10 &  然后 echo $!

# --- $_ ---
# 上一个命令的最后一个参数
echo "上一个命令的最后一个参数(\$_)：$_"

echo ""
echo "========== 脚本结束 =========="
echo "恭喜你完成了第一个 Shell 脚本的学习！"
echo "接下来可以学习 02_variables.sh 了解更多变量操作"

# 脚本正常结束，返回退出码 0
# exit 0  可以显式指定退出码，不写的话默认以最后一条命令的状态退出

// ============================================================
// 模块名：mux4to1
// 功能描述：4选1多路选择器（数据选择器）
//           演示多路选择器原理、case语句、三元运算符对比
// 输入端口：
//   data_in  - 输入数据，4路，每路4位
//              data_in[0] 对应第0路输入
//              data_in[1] 对应第1路输入
//              data_in[2] 对应第2路输入
//              data_in[3] 对应第3路输入
//   sel      - 选择信号，2位
//              2位选择信号可以选择4路输入中的1路
// 输出端口：
//   data_out_case  - 使用case语句实现的输出
//   data_out_ternary - 使用嵌套三元运算符实现的输出
//   data_out_assign - 使用assign+case方式的输出（generate块）
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

module mux4to1 (
    input  [3:0][3:0] data_in,       // 4路输入数据，每路4位
                                    // [3:0] 表示4路，第二个[3:0]表示每路4位
                                    // SystemVerilog语法，部分综合工具可能不支持
                                    // 传统写法可用4个独立输入或拼接
    input  [1:0]       sel,          // 选择信号，2位（00/01/10/11）
    output reg [3:0]   data_out_case,     // case语句实现
    output     [3:0]   data_out_ternary,  // 三元运算符实现
    output reg [3:0]   data_out_if         // if-else实现
);

// ============================================================
// 一、多路选择器（MUX）基本原理
// ============================================================
//
// 多路选择器（Multiplexer，简称MUX）是一种组合逻辑电路，
// 它的功能是根据选择信号，从多路输入数据中选择一路输出。
//
// 4选1多路选择器的真值表：
//   sel[1] | sel[0] | data_out
//   -------+--------+----------
//     0    |   0    | data_in[0]
//     0    |   1    | data_in[1]
//     1    |   0    | data_in[2]
//     1    |   1    | data_in[3]
//
// 一般地，N位选择信号可以选择 2^N 路输入。
// 例如：1位→2选1，2位→4选1，3位→8选1，4位→16选1
//
// 多路选择器的应用：
//   1. 数据通路选择：在多个数据源之间切换
//   2. 函数发生器：用MUX实现任意组合逻辑函数
//   3. 总线复用：时分复用总线，多个设备共享一条总线
//   4. ALU操作选择：选择不同的运算操作
// ============================================================

// ============================================================
// 二、case语句实现（推荐方式）
// ============================================================
//
// case 语句是 Verilog 中实现多路选择最清晰、最常用的方式。
// 语法：
//   case (表达式)
//       情况1: 语句1;
//       情况2: 语句2;
//       ...
//       default: 默认语句;
//   endcase
//
// 特点：
//   1. 根据表达式的值，匹配对应的情况分支
//   2. 分支是并行的，没有优先级之分
//   3. default 分支是可选的，但建议加上，避免生成锁存器
//   4. 只能在 always 块中使用
// ============================================================

// always @(*) 表示组合逻辑，敏感列表包含所有右侧信号
always @(*) begin
    // 根据 sel 的值选择对应的输入
    case (sel)
        2'b00:  data_out_case = data_in[0];  // sel=00，选第0路
        2'b01:  data_out_case = data_in[1];  // sel=01，选第1路
        2'b10:  data_out_case = data_in[2];  // sel=10，选第2路
        2'b11:  data_out_case = data_in[3];  // sel=11，选第3路
        default: data_out_case = 4'd0;       // 默认情况，避免锁存器
    endcase
end

// 【知识点】为什么需要 default 分支？
// 在组合逻辑 always 块中，如果某个分支没有给输出赋值，
// 综合工具会认为输出需要"保持"原来的值，从而生成锁存器（Latch）。
// 锁存器是电平敏感的存储单元，在设计中应尽量避免：
//   1. 锁存器会引入时序问题（毛刺、竞争冒险）
//   2. FPGA 中锁存器资源有限，不如触发器高效
//   3. 静态时序分析（STA）对锁存器支持较差
// 所以，组合逻辑 always 块中一定要确保所有可能的情况下
// 输出都有赋值，default 分支就是起这个作用。

// ============================================================
// 三、三元运算符（条件运算符）实现
// ============================================================
//
// 三元运算符语法：condition ? true_value : false_value
// 可以嵌套使用，实现多路选择。
//
// 特点：
//   1. 可以在 assign 语句中直接使用，不需要 always 块
//   2. 适合简单的2选1或少量路数的选择
//   3. 嵌套太深会降低可读性
//   4. 生成的电路与 case 语句相同
// ============================================================

// 嵌套三元运算符实现4选1
// 第一层判断 sel[1]（高位），第二层判断 sel[0]（低位）
assign data_out_ternary = sel[1] ? 
                            (sel[0] ? data_in[3] : data_in[2]) :  // sel=1x
                            (sel[0] ? data_in[1] : data_in[0]);   // sel=0x

// 上面的代码等价于：
// sel=00 → data_in[0]
// sel=01 → data_in[1]
// sel=10 → data_in[2]
// sel=11 → data_in[3]

// ============================================================
// 四、if-else 语句实现
// ============================================================
//
// if-else 语句也可以实现多路选择，但有一个重要区别：
// if-else 是有优先级的，先写的条件优先级高。
// 而 case 语句的各个分支是平级的，没有优先级。
//
// 对于多路选择器这种不需要优先级的场景，
// 用 case 语句更合适，综合结果也更优化。
// ============================================================

always @(*) begin
    if (sel == 2'b00)
        data_out_if = data_in[0];
    else if (sel == 2'b01)
        data_out_if = data_in[1];
    else if (sel == 2'b10)
        data_out_if = data_in[2];
    else
        data_out_if = data_in[3];  // 等价于 sel == 2'b11
end

// ============================================================
// 五、三种实现方式对比
// ============================================================
//
// | 实现方式   | 可读性 | 适用场景           | 是否有优先级 |
// |-----------+--------+-------------------+-------------|
// | case      | 好     | 多路选择（4路以上） | 否（平级）  |
// | 三元运算符 | 一般   | 2选1或简单3选1     | 否（平级）  |
// | if-else   | 一般   | 有优先级的判断     | 是（有优先级）|
//
// 选择建议：
//   1. 多路数据选择 → 用 case
//   2. 简单2选1 → 用三元运算符（一行搞定）
//   3. 有优先级的判断 → 用 if-else
//   4. 组合逻辑中务必覆盖所有情况，避免生成锁存器
//
// 【重要】对于多路选择器，case 语句是最佳选择，
// 因为它清晰地表达了"多路选一"的语义，
// 综合工具也能更好地优化成 MUX 结构。
// ============================================================


// ============================================================
// 模块名：encoder8to3
// 功能描述：8-3编码器
//           演示普通编码器、优先编码器原理
// 输入端口：
//   in       - 8位输入（独热码形式）
// 输出端口：
//   out_normal  - 普通编码器输出（3位二进制）
//   valid_normal - 普通编码器有效标志
//   out_priority - 优先编码器输出（3位二进制）
//   valid_priority - 优先编码器有效标志
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

module encoder8to3 (
    input       [7:0]  in,             // 8位输入
    output reg  [2:0]  out_normal,     // 普通编码器输出
    output reg         valid_normal,   // 普通编码器有效标志
    output reg  [2:0]  out_priority,   // 优先编码器输出
    output reg         valid_priority  // 优先编码器有效标志
);

// ============================================================
// 一、编码器基本原理
// ============================================================
//
// 编码器（Encoder）是译码器的逆过程：
//   译码器：二进制码 → 独热码（one-hot）
//   编码器：独热码 → 二进制码
//
// 8-3编码器：8位输入，3位输出
// 8个输入中只有1个有效（为1），输出对应的3位二进制编码。
//
// 普通编码器真值表（高有效输入）：
//   in[7:0] | out[2:0]
//   --------+----------
//   00000001 |   000    （第0位有效 → 编码为0）
//   00000010 |   001    （第1位有效 → 编码为1）
//   00000100 |   010    （第2位有效 → 编码为2）
//   00001000 |   011    （第3位有效 → 编码为3）
//   00010000 |   100    （第4位有效 → 编码为4）
//   00100000 |   101    （第5位有效 → 编码为5）
//   01000000 |   110    （第6位有效 → 编码为6）
//   10000000 |   111    （第7位有效 → 编码为7）
//
// 编码器的应用：
//   1. 键盘扫描：将按键位置编码为二进制码
//   2. 中断优先级：多个中断源中优先级最高的编码
//   3. 数据压缩：将独热码转换为二进制码，节省位宽
// ============================================================

// ============================================================
// 二、普通编码器
// ============================================================
//
// 普通编码器的特点：
//   1. 任何时刻只允许一个输入有效
//   2. 如果同时有多个输入有效，输出是不确定的
//   3. 没有输入有效时，输出无意义
//
// 因此，普通编码器需要一个 valid 标志位，
// 表示当前输出是否有效。
// ============================================================

always @(*) begin
    // 默认值，避免生成锁存器
    out_normal = 3'b000;
    valid_normal = 1'b0;
    
    case (in)
        8'b0000_0001: begin
            out_normal = 3'b000;   // 第0位有效 → 编码0
            valid_normal = 1'b1;   // 输出有效
        end
        8'b0000_0010: begin
            out_normal = 3'b001;   // 第1位有效 → 编码1
            valid_normal = 1'b1;
        end
        8'b0000_0100: begin
            out_normal = 3'b010;   // 第2位有效 → 编码2
            valid_normal = 1'b1;
        end
        8'b0000_1000: begin
            out_normal = 3'b011;   // 第3位有效 → 编码3
            valid_normal = 1'b1;
        end
        8'b0001_0000: begin
            out_normal = 3'b100;   // 第4位有效 → 编码4
            valid_normal = 1'b1;
        end
        8'b0010_0000: begin
            out_normal = 3'b101;   // 第5位有效 → 编码5
            valid_normal = 1'b1;
        end
        8'b0100_0000: begin
            out_normal = 3'b110;   // 第6位有效 → 编码6
            valid_normal = 1'b1;
        end
        8'b1000_0000: begin
            out_normal = 3'b111;   // 第7位有效 → 编码7
            valid_normal = 1'b1;
        end
        default: begin
            // 其他情况：没有输入有效，或多个输入同时有效
            out_normal = 3'b000;   // 输出无意义
            valid_normal = 1'b0;   // 输出无效
        end
    endcase
end

// 【普通编码器的局限性】
// 普通编码器要求同一时刻只能有一个输入有效，
// 这在实际应用中往往难以保证。
// 例如：键盘输入时可能同时按下多个键。
// 为了解决这个问题，引入了"优先编码器"。

// ============================================================
// 三、优先编码器
// ============================================================
//
// 优先编码器（Priority Encoder）的特点：
//   1. 允许同时有多个输入有效
//   2. 每个输入有不同的优先级
//   3. 输出优先级最高的那个输入的编码
//   4. 没有输入有效时，valid=0
//
// 通常规定：高位优先级高，低位优先级低。
// 即 in[7] 优先级最高，in[0] 优先级最低。
//
// 优先编码器真值表（部分）：
//   in[7] in[6] ... in[0] | out  | valid
//   ------+-------+-------+------+------
//     1     x   ...  x    | 111  |  1   （第7位最高优先级）
//     0     1   ...  x    | 110  |  1   （第6位次高）
//     0     0   ...  x    | ...  | ...
//     0     0   ...  1    | 000  |  1   （第0位最低）
//     0     0   ...  0    | xxx  |  0   （无输入有效）
//
// x 表示"不关心"，可以是0或1。
// ============================================================

// 优先编码器实现方式一：if-else 语句
// 因为 if-else 有优先级（先判断的优先级高），
// 所以非常适合实现优先编码器。
always @(*) begin
    // 默认值
    out_priority = 3'b000;
    valid_priority = 1'b0;
    
    // 从最高位到最低位依次判断
    // 先判断的优先级高
    if (in[7]) begin
        out_priority = 3'b111;    // 第7位 → 编码7（最高优先级）
        valid_priority = 1'b1;
    end
    else if (in[6]) begin
        out_priority = 3'b110;    // 第6位 → 编码6
        valid_priority = 1'b1;
    end
    else if (in[5]) begin
        out_priority = 3'b101;    // 第5位 → 编码5
        valid_priority = 1'b1;
    end
    else if (in[4]) begin
        out_priority = 3'b100;    // 第4位 → 编码4
        valid_priority = 1'b1;
    end
    else if (in[3]) begin
        out_priority = 3'b011;    // 第3位 → 编码3
        valid_priority = 1'b1;
    end
    else if (in[2]) begin
        out_priority = 3'b010;    // 第2位 → 编码2
        valid_priority = 1'b1;
    end
    else if (in[1]) begin
        out_priority = 3'b001;    // 第1位 → 编码1
        valid_priority = 1'b1;
    end
    else if (in[0]) begin
        out_priority = 3'b000;    // 第0位 → 编码0（最低优先级）
        valid_priority = 1'b1;
    end
    else begin
        // 没有输入有效
        out_priority = 3'b000;
        valid_priority = 1'b0;
    end
end

// 【知识点】为什么优先编码器用 if-else 而不用 case？
// 因为 case 语句的各个分支是平级的，没有优先级，
// 而 if-else 是串行判断的，先写的条件优先级高。
// 优先编码器恰好需要"优先级"这个特性，
// 所以 if-else 是最自然的实现方式。

// ============================================================
// 四、优先编码器的另一种实现：casez
// ============================================================
//
// 利用 casez 的"不关心位"特性，也可以实现优先编码器。
// 写法上比 if-else 更简洁。
// ============================================================
/*
// casez 实现优先编码器（示例代码）
always @(*) begin
    out_priority = 3'b000;
    valid_priority = 1'b0;
    
    casez (in)
        8'b1???????: begin  // 第7位为1，其他位不关心
            out_priority = 3'b111;
            valid_priority = 1'b1;
        end
        8'b01??????: begin  // 第6位为1，第7位为0，其他不关心
            out_priority = 3'b110;
            valid_priority = 1'b1;
        end
        8'b001?????: begin  // 第5位为1
            out_priority = 3'b101;
            valid_priority = 1'b1;
        end
        // ... 以此类推
        8'b00000001: begin
            out_priority = 3'b000;
            valid_priority = 1'b1;
        end
        default: begin
            out_priority = 3'b000;
            valid_priority = 1'b0;
        end
    endcase
end
*/
// casez 实现优先编码器的关键：
// 分支的顺序很重要！casez 按从上到下的顺序匹配，
// 先匹配到的分支生效，所以要把高优先级的写在前面。

// ============================================================
// 五、普通编码器 vs 优先编码器
// ============================================================
//
// | 特性         | 普通编码器       | 优先编码器           |
// |-------------+-----------------+---------------------|
// | 输入约束     | 同一时刻只能1个有效 | 允许多个同时有效      |
// | 优先级       | 无              | 有（通常高位优先）     |
// | 实现方式     | case 语句       | if-else 或 casez     |
// | 应用场景     | 输入互斥的场景   | 中断、键盘、仲裁等    |
//
// 实际工程中，优先编码器比普通编码器更常用，
// 因为它的容错性更好，适用场景更广。
// ============================================================

// ============================================================
// 六、编码器 vs 译码器
// ============================================================
//
// 编码器和译码器是互逆的操作：
//
// 编码器（Encoder）：
//   输入：独热码（2^N位，只有1位为1）
//   输出：二进制码（N位）
//   功能：压缩位宽
//
// 译码器（Decoder）：
//   输入：二进制码（N位）
//   输出：独热码（2^N位，只有1位为1）
//   功能：扩展位宽
//
// 记忆口诀：
//   编码：多 → 少（压缩）
//   译码：少 → 多（展开）
//
// 组合使用：
//   在数字系统中，经常需要"编码 → 传输 → 译码"的流程，
//   这样可以减少传输线的数量（因为编码后位宽更窄）。
// ============================================================

endmodule

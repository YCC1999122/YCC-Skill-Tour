// ============================================================
// 模块名：decoder3to8
// 功能描述：3-8译码器
//           演示译码器原理、casez/casex用法、7段数码管译码器
// 输入端口：
//   in       - 3位二进制输入
//   en       - 使能信号，高有效
// 输出端口：
//   out_case  - 使用case语句实现的译码输出（8位，高有效）
//   out_assign - 使用assign语句实现的译码输出（8位）
//   seg_out   - 7段数码管译码输出（共阴极）
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

module decoder3to8 (
    input       [2:0]  in,          // 3位二进制输入
    input              en,          // 使能信号，高有效
    output reg  [7:0]  out_case,    // case语句译码输出
    output      [7:0]  out_assign,  // assign语句译码输出
    output reg  [6:0]  seg_out      // 7段数码管译码输出
);

// ============================================================
// 一、译码器基本原理
// ============================================================
//
// 译码器（Decoder）是一种组合逻辑电路，
// 它的功能是将输入的二进制代码翻译成对应的输出信号。
//
// 3-8译码器：3位输入，8位输出
// 每输入一组3位二进制码，8个输出中只有对应的1个有效。
//
// 真值表（高有效输出，使能en=1时工作）：
//   in[2:0] | out[7] out[6] ... out[0]
//   --------+------------------------
//    000    |   0     0   ...   1    （第0位有效）
//    001    |   0     0   ...   0    （第1位有效）
//    010    |   0     0   ...   0    （第2位有效）
//    011    |   0     0   ...   0    （第3位有效）
//    100    |   0     0   ...   0    （第4位有效）
//    101    |   0     0   ...   0    （第5位有效）
//    110    |   1     0   ...   0    （第6位有效）
//    111    |   0     1   ...   0    （第7位有效）
//
// 一般地，N位输入 → 2^N位输出。
//
// 译码器的应用：
//   1. 地址译码：存储器、IO端口的地址选择
//   2. 数据分配：将一路数据分配到多个通道（DEMUX）
//   3. 数码显示：7段数码管译码（BCD→7段）
//   4. 指令译码：CPU中对操作码进行译码
// ============================================================

// ============================================================
// 二、case语句实现3-8译码器
// ============================================================
//
// 使用 case 语句逐一列出每种输入对应的输出。
// 当使能信号 en=0 时，所有输出都为0。
// ============================================================

always @(*) begin
    if (!en) begin
        // 使能无效，所有输出为0
        out_case = 8'b0000_0000;
    end
    else begin
        // 使能有效，根据输入译码
        case (in)
            3'b000:  out_case = 8'b0000_0001;  // 第0位输出有效
            3'b001:  out_case = 8'b0000_0010;  // 第1位输出有效
            3'b010:  out_case = 8'b0000_0100;  // 第2位输出有效
            3'b011:  out_case = 8'b0000_1000;  // 第3位输出有效
            3'b100:  out_case = 8'b0001_0000;  // 第4位输出有效
            3'b101:  out_case = 8'b0010_0000;  // 第5位输出有效
            3'b110:  out_case = 8'b0100_0000;  // 第6位输出有效
            3'b111:  out_case = 8'b1000_0000;  // 第7位输出有效
            default: out_case = 8'b0000_0000;  // 默认全0
        endcase
    end
end

// ============================================================
// 三、assign语句实现3-8译码器
// ============================================================
//
// 使用位选的方式，直接将1移到对应的位置。
// 这种写法更简洁，也更容易参数化。
// ============================================================

// 1 << in 表示将1左移in位
// 例如：in=3 → 1<<3 = 8'b0000_1000
// en ? (...) : 8'd0 表示使能有效时才输出译码结果
assign out_assign = en ? (8'b1 << in) : 8'b0000_0000;

// 【知识点】移位运算符
// <<  ：逻辑左移，右侧补0
// >>  ：逻辑右移，左侧补0（对无符号数）
// <<< ：算术左移（与逻辑左移相同）
// >>> ：算术右移，左侧补符号位（对有符号数）
//
// 这里用 1 << in 实现译码，是一种非常巧妙的写法，
// 综合效果与 case 语句相同，但代码更简洁。

// ============================================================
// 四、casez / casex 语句详解
// ============================================================
//
// Verilog 中有三种 case 语句：
//   1. case   ：精确匹配，0和1都要匹配，x和z也参与比较
//   2. casez  ：不关心高阻态 z，z 被当作"不关心"
//   3. casex  ：不关心 x 和 z，x 和 z 都被当作"不关心"
//
// 语法上，用 ? 表示不关心的位（等价于 z）。
//
// 【注意】
//   - casez/casex 常用于有"不关心"位的译码场景
//   - 实际综合时，不关心的位不会参与判断
//   - 仿真中要注意 x 的传播问题，casex 可能会隐藏问题
//   - 推荐使用 casez，尽量避免 casex
// ============================================================

// 下面用 casez 实现一个带使能的译码器示例（仅演示语法）
// synthesis translate_off
reg [7:0] out_casez_demo;
always @(*) begin
    casez ({en, in})    // {en, in} 是拼接，共4位
        4'b1???: out_casez_demo = 8'b1 << in;  // en=1时，in的3位正常译码
        4'b0???: out_casez_demo = 8'b0;         // en=0时，输出全0
    endcase
end
// synthesis translate_on

// 【知识点】不关心位（Don't Care）
// 在 casez 中，? 或 z 表示该位不参与比较。
// 例如 4'b1??? 表示第3位（en）必须是1，低3位可以是任意值。
// 这在处理有使能信号的译码时非常方便。

// ============================================================
// 五、7段数码管译码器
// ============================================================
//
// 7段数码管是最常用的数字显示器件，由7个发光二极管组成。
// 通过控制不同段的亮灭，可以显示0-9和部分字母。
//
// 7段数码管的段命名：
//       a
//     -----
//    |     |
//   f|     |b
//    |  g  |
//     -----
//    |     |
//   e|     |c
//    |  d  |
//     -----   . dp（小数点）
//
// 共阴极 vs 共阳极：
//   - 共阴极：所有LED阴极连在一起接地，阳极接高电平点亮
//             输出1表示点亮，输出0表示熄灭
//   - 共阳极：所有LED阳极连在一起接VCC，阴极接低电平点亮
//             输出0表示点亮，输出1表示熄灭
//
// 本模块使用共阴极接法，输出高电平点亮。
// 段码顺序：seg_out[6:0] = {a, b, c, d, e, f, g}
// ============================================================

// 7段数码管译码器
// 输入为4位BCD码（0-9），输出7段显示码
// 输入超过9时，显示横杠"-"（仅g段亮）
always @(*) begin
    case (in)  // in是3位，这里只用低3位演示
        // in=0 → 显示0（a,b,c,d,e,f亮，g灭）
        3'b000:  seg_out = 7'b111_1110;  // 0
        // in=1 → 显示1（b,c亮）
        3'b001:  seg_out = 7'b011_0000;  // 1
        // in=2 → 显示2（a,b,g,e,d亮）
        3'b010:  seg_out = 7'b110_1101;  // 2
        // in=3 → 显示3（a,b,g,c,d亮）
        3'b011:  seg_out = 7'b111_1001;  // 3
        // in=4 → 显示4（f,g,b,c亮）
        3'b100:  seg_out = 7'b011_0011;  // 4
        // in=5 → 显示5（a,f,g,c,d亮）
        3'b101:  seg_out = 7'b101_1011;  // 5
        // in=6 → 显示6（a,f,g,c,d,e亮）
        3'b110:  seg_out = 7'b101_1111;  // 6
        // in=7 → 显示7（a,b,c亮）
        3'b111:  seg_out = 7'b111_0000;  // 7
        default: seg_out = 7'b000_0000;  // 默认全灭
    endcase
end

// 【7段数码管段码表（共阴极）】
// 数字 | a b c d e f g | 十六进制
// ----+---------------+---------
//  0  | 1 1 1 1 1 1 0 | 7'h7E
//  1  | 0 1 1 0 0 0 0 | 7'h30
//  2  | 1 1 0 1 1 0 1 | 7'h6D
//  3  | 1 1 1 1 0 0 1 | 7'h79
//  4  | 0 1 1 0 0 1 1 | 7'h33
//  5  | 1 0 1 1 0 1 1 | 7'h5B
//  6  | 1 0 1 1 1 1 1 | 7'h5F
//  7  | 1 1 1 0 0 0 0 | 7'h70
//  8  | 1 1 1 1 1 1 1 | 7'h7F
//  9  | 1 1 1 1 0 1 1 | 7'h7B
//  A  | 1 1 1 0 1 1 1 | 7'h77
//  b  | 0 0 1 1 1 1 1 | 7'h1F
//  C  | 1 0 0 1 1 1 0 | 7'h4E
//  d  | 0 1 1 1 1 0 1 | 7'h3D
//  E  | 1 0 0 1 1 1 1 | 7'h4F
//  F  | 1 0 0 0 1 1 1 | 7'h47
//  -  | 0 0 0 0 0 0 1 | 7'h01
//  灭 | 0 0 0 0 0 0 0 | 7'h00

// ============================================================
// 六、译码器 vs 多路选择器
// ============================================================
//
// 译码器和多路选择器是一对"互补"的电路：
//
// 多路选择器（MUX）：多输入，单输出
//   - 根据选择信号，从多路输入中选一路输出
//   - 功能：多选一
//
// 译码器（Decoder）：单输入（二进制码），多输出
//   - 根据输入的二进制码，使对应的输出有效
//   - 功能：二进制码 → 独热码
//
// 联系：
//   译码器 + 数据输入 = 数据分配器（DEMUX）
//   多路选择器 = 数据选择器
//
// 在实际数字系统中，译码器常用于地址译码、
// 指令译码等场景，是非常基础和重要的组合逻辑单元。
// ============================================================

endmodule

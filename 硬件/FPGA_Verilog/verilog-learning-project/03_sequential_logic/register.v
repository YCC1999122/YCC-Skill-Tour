// ============================================================
// 模块名：register
// 功能描述：寄存器设计
//           演示D触发器、寄存器堆、移位寄存器、环移/扭环移位寄存器
// 输入端口：
//   clk      - 系统时钟，上升沿触发
//   rst_n    - 复位信号，低有效，异步复位
//   d        - D触发器输入数据
//   wr_en    - 寄存器堆写使能
//   wr_addr  - 寄存器堆写地址，2位（4个寄存器）
//   wr_data  - 寄存器堆写数据
//   rd_addr  - 寄存器堆读地址，2位
//   shift_in - 移位寄存器串行输入
//   shift_en - 移位使能信号
// 输出端口：
//   q_dff       - D触发器输出
//   rd_data     - 寄存器堆读数据
//   shift_out   - 移位寄存器串行输出
//   shift_par_out - 移位寄存器并行输出（4位）
//   ring_out    - 环形移位寄存器输出（4位）
//   twisted_out - 扭环移位寄存器输出（4位）
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

module register (
    input              clk,            // 系统时钟
    input              rst_n,          // 复位信号，低有效
    input              d,              // D触发器输入
    input              wr_en,          // 寄存器堆写使能
    input       [1:0]  wr_addr,        // 寄存器堆写地址
    input       [3:0]  wr_data,        // 寄存器堆写数据
    input       [1:0]  rd_addr,        // 寄存器堆读地址
    input              shift_in,       // 移位寄存器串行输入
    input              shift_en,       // 移位使能
    output reg         q_dff,          // D触发器输出
    output reg  [3:0]  rd_data,        // 寄存器堆读数据
    output             shift_out,      // 移位寄存器串行输出
    output      [3:0]  shift_par_out,  // 移位寄存器并行输出
    output reg  [3:0]  ring_out,       // 环形移位寄存器输出
    output reg  [3:0]  twisted_out     // 扭环移位寄存器输出
);

// ============================================================
// 一、D触发器（D Flip-Flop）
// ============================================================
//
// D触发器是最基本的时序逻辑单元，也是所有寄存器的基础。
// D = Data（数据），所以叫D触发器。
//
// 功能：在时钟边沿（通常是上升沿），将输入D的值存入触发器，
//       输出Q更新为D的值。在其他时间，Q保持不变。
//
// 真值表（上升沿触发）：
//   clk   | rst_n | D | Q（次态）
//   ------+-------+---+----------
//    ↑    |   0   | x |   0     （复位有效，异步复位）
//    ↑    |   1   | 0 |   0     （置0）
//    ↑    |   1   | 1 |   1     （置1）
//   不变  |   1   | x | 保持    （没有时钟沿，保持原值）
//
// 符号说明：
//   ↑ 表示时钟上升沿（posedge）
//   x 表示任意值
//
// 建立时间（Setup Time, Tsu）：
//   D信号必须在时钟沿到来之前稳定的最小时间。
//   如果不满足，触发器可能进入亚稳态。
//
// 保持时间（Hold Time, Th）：
//   D信号必须在时钟沿到来之后继续保持稳定的最小时间。
//
// 时钟到输出延迟（Clock-to-Q Delay, Tco）：
//   从时钟沿到Q端输出更新的延迟。
// ============================================================

// D触发器实现（异步复位）
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // 复位有效，输出置0
        q_dff <= 1'b0;
    end
    else begin
        // 时钟上升沿，将d存入触发器
        q_dff <= d;
    end
end

// 【知识点】同步复位 vs 异步复位
//
// 异步复位（上面的写法）：
//   always @(posedge clk or negedge rst_n)
//   复位信号在敏感列表中，复位立即生效，不依赖时钟。
//   优点：复位响应快，不依赖时钟，复位树简单
//   缺点：复位释放时可能产生亚稳态（复位异步释放）
//
// 同步复位：
//   always @(posedge clk)
//   复位只在时钟上升沿被采样。
//   优点：复位同步于时钟，亚稳态风险低
//   缺点：复位必须持续到下一个时钟沿，需要时钟才能复位
//
// 工程实践：
//   大多数设计采用"异步复位，同步释放"的方案，
//   兼顾复位响应速度和释放时的稳定性。

// ============================================================
// 二、寄存器堆（Register File）
// ============================================================
//
// 寄存器堆是一组寄存器的集合，通常用于：
//   - CPU 中的通用寄存器组
//   - 数据缓存
//   - 流水线中的数据暂存
//
// 特点：
//   - 多个寄存器共享读写端口
//   - 通过地址选择读写哪个寄存器
//   - 通常有多个读端口和1个写端口
//
// 本模块实现一个简单的 4 x 4 寄存器堆：
//   - 4个寄存器
//   - 每个寄存器4位宽
//   - 1个写端口 + 1个读端口
// ============================================================

// 2.1 定义寄存器数组
// reg [位宽-1:0] 数组名 [深度-1:0];
reg [3:0] reg_file [3:0];  // 4个4位寄存器

// 2.2 写操作（时序逻辑）
// 写操作是同步的，只有在时钟上升沿且写使能有效时才写入
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // 复位时所有寄存器清0
        reg_file[0] <= 4'd0;
        reg_file[1] <= 4'd0;
        reg_file[2] <= 4'd0;
        reg_file[3] <= 4'd0;
    end
    else if (wr_en) begin
        // 写使能有效时，根据写地址写入对应寄存器
        reg_file[wr_addr] <= wr_data;
    end
    // 写使能无效时，所有寄存器保持原值
end

// 2.3 读操作（组合逻辑）
// 读操作是异步的，地址变化后立即输出对应寄存器的值
always @(*) begin
    rd_data = reg_file[rd_addr];
end

// 【知识点】寄存器数组
// Verilog 中定义寄存器数组的语法：
//   reg [位宽-1:0] 数组名 [个数-1:0];
// 例如：reg [7:0] mem [255:0];  // 256个8位寄存器
//
// 注意两个维度的含义：
//   - 左边的 [7:0] 是每个寄存器的位宽
//   - 右边的 [255:0] 是寄存器的个数（深度）
//
// 访问方式：数组名[地址]
// 例如：mem[10] 表示第10个8位寄存器

// 【知识点】读操作的实现方式
// 方式一：组合逻辑 always @(*) → 异步读（本模块采用）
//   优点：读延迟为0，地址一变就输出
//   缺点：可能产生组合逻辑延迟和毛刺
//
// 方式二：时序逻辑 always @(posedge clk) → 同步读
//   优点：输出稳定，没有毛刺
//   缺点：读延迟为1个时钟周期
//
// 实际工程中，FPGA 的 Block RAM 通常是同步读，
// 而分布式 RAM / 寄存器堆可以是异步读。

// ============================================================
// 三、移位寄存器（Shift Register）
// ============================================================
//
// 移位寄存器：在时钟作用下，将存储的数据依次向左或向右移动。
//
// 分类：
//   - 串入串出（SISO）：串行输入，串行输出
//   - 串入并出（SIPO）：串行输入，并行输出
//   - 并入串出（PISO）：并行输入，串行输出
//   - 并入并出（PIPO）：并行输入，并行输出（就是普通寄存器）
//
// 应用：
//   1. 串并转换：串行数据 → 并行数据（或反之）
//   2. 数据延迟：将信号延迟N个时钟周期
//   3. 计数器：环形计数器、扭环计数器
//   4. 伪随机序列生成（LFSR）
// ============================================================

// 3.1 4位右移移位寄存器（串入串出/串入并出）
// 串行输入 shift_in 从最高位移入，最低位移出
// 每来一个时钟，所有位向右移一位
reg [3:0] shift_reg;    // 移位寄存器

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        shift_reg <= 4'd0;
    end
    else if (shift_en) begin
        // 移位使能有效时，右移一位
        // {shift_in, shift_reg[3:1]} 表示：
        //   把 shift_in 放在最高位，原来的高3位移到低3位
        // 效果：整体向右移一位，最高位补 shift_in
        shift_reg <= {shift_in, shift_reg[3:1]};
    end
    // 移位使能无效时，保持原值
end

// 串行输出 = 最低位（每次右移，从最低位移出）
assign shift_out = shift_reg[0];

// 并行输出 = 整个寄存器的值
assign shift_par_out = shift_reg;

// 【知识点】移位的 Verilog 写法
// 右移一位（高位补xin）：reg <= {xin, reg[N-1:1]};
// 左移一位（低位补xin）：reg <= {reg[N-2:0], xin};
//
// 用拼接运算符 { } 实现移位是最常用的写法，
// 比移位运算符 >> 更直观，也更容易控制移入的值。

// 【移位寄存器的延迟作用】
// N位移位寄存器可以将串行信号延迟N个时钟周期。
// 例如：4位移位寄存器，输入从 shift_in 进去，
// 经过4个时钟周期后从 shift_out 出来，延迟了4拍。
// 这在数字电路中常用于时序对齐。

// ============================================================
// 四、环形移位寄存器（Ring Shift Register）
// ============================================================
//
// 环形移位寄存器：将移位寄存器的输出反馈回输入，形成一个环。
// 也就是把最后一位的输出接到第一位的输入。
//
// 结构示意（4位）：
//   ┌───────────────────────────────┐
//   ↓                               │
//  ┌───┐   ┌───┐   ┌───┐   ┌───┐  │
//  │FF0│←──│FF1│←──│FF2│←──│FF3│←──┘
//  └───┘   └───┘   └───┘   └───┘
//
// 工作过程（假设初始值为 1000）：
//   第0拍：1000  （初始状态）
//   第1拍：0100  （右移一位，最后一位循环到最前面）
//   第2拍：0010
//   第3拍：0001
//   第4拍：1000  （回到初始状态，循环）
//
// 特点：
//   - N位环形移位寄存器有 N 个有效状态
//   - 状态中只有1个1（或只有1个0）在循环移动
//   - 可以作为独热码计数器使用
// ============================================================

// 环形移位寄存器（右移，最低位循环到最高位）
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // 初始值设为 1000，只有一个1
        ring_out <= 4'b1000;
    end
    else if (shift_en) begin
        // 右移一位，最低位移到最高位（循环）
        // ring_out[0] 是最低位，接到最高位输入
        ring_out <= {ring_out[0], ring_out[3:1]};
    end
end

// 【环形移位寄存器作为计数器】
// 环形移位寄存器的状态数等于位数（4位→4个状态）。
// 优点：输出是独热码，不需要译码
// 缺点：状态利用率低，N位只有N个状态（普通二进制计数器有2^N个）

// ============================================================
// 五、扭环移位寄存器（Twisted Ring / Johnson Counter）
// ============================================================
//
// 扭环移位寄存器：也叫约翰逊计数器（Johnson Counter），
// 将最后一位的输出取反后反馈回输入。
//
// 结构示意（4位）：
//   ┌─────────────── NOT ───────────┐
//   ↓                               │
//  ┌───┐   ┌───┐   ┌───┐   ┌───┐  │
//  │FF0│←──│FF1│←──│FF2│←──│FF3│←──┘
//  └───┘   └───┘   └───┘   └───┘
//
// 工作过程（初始值为 0000）：
//   第0拍：0000  （初始状态）
//   第1拍：1000  （最低位0取反=1，移到最高位）
//   第2拍：1100
//   第3拍：1110
//   第4拍：1111
//   第5拍：0111  （最低位1取反=0，移到最高位）
//   第6拍：0011
//   第7拍：0001
//   第8拍：0000  （回到初始状态，循环）
//
// 特点：
//   - N位扭环移位寄存器有 2N 个有效状态
//   - 状态变化是连续的，相邻状态只有1位不同（格雷码特性）
//   - 译码简单，不会产生毛刺
// ============================================================

// 扭环移位寄存器（右移，最低位取反后移到最高位）
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // 初始值设为全0
        twisted_out <= 4'b0000;
    end
    else if (shift_en) begin
        // 右移一位，最低位取反后移到最高位
        twisted_out <= {~twisted_out[0], twisted_out[3:1]};
    end
end

// 【扭环计数器 vs 二进制计数器】
//
// | 特性         | 扭环计数器     | 二进制计数器 |
// |-------------+---------------+-------------|
// | N位状态数    | 2N            | 2^N         |
// | 状态编码     | 格雷码特性     | 二进制       |
// | 译码毛刺     | 无            | 可能有       |
// | 状态利用率   | 低            | 高          |
// | 适用场景     | 状态少、需无毛刺译码 | 通用计数  |
//
// 扭环计数器常用于：
//   - 时序控制（产生多相时钟）
//   - 低毛刺的状态机
//   - 环形振荡器

// ============================================================
// 六、各种寄存器总结
// ============================================================
//
// | 寄存器类型     | 功能描述             | 典型应用           |
// |---------------+---------------------+-------------------|
// | D触发器       | 1位数据存储          | 最基本时序单元      |
// | 寄存器堆      | 多寄存器读写         | CPU通用寄存器组     |
// | 移位寄存器    | 数据移位             | 串并转换、延迟线    |
// | 环形移位寄存器 | 数据循环移位         | 独热码计数器        |
// | 扭环移位寄存器 | 数据扭环循环         | 约翰逊计数器、多相时钟 |
//
// 所有这些寄存器都是由D触发器组成的，
// 只是连接方式不同，功能就不同。
// D触发器是时序逻辑的基础，理解D触发器是关键。
// ============================================================

endmodule

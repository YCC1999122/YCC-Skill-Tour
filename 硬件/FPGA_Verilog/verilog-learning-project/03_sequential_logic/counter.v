// ============================================================
// 模块名：counter
// 功能描述：计数器设计
//           演示二进制计数器、BCD计数器、模N计数器、加减可逆计数器
// 输入端口：
//   clk      - 系统时钟，上升沿触发
//   rst_n    - 复位信号，低有效，异步复位
//   en       - 计数使能信号，高有效
//   up_down  - 加减控制，1为加计数，0为减计数
// 输出端口：
//   bin_cnt     - 4位二进制计数器输出
//   bin_carry   - 二进制计数器进位输出
//   bcd_cnt     - BCD计数器输出（8位，2位十进制）
//   bcd_carry   - BCD计数器进位输出
//   mod6_cnt    - 模6计数器输出
//   mod6_carry  - 模6计数器进位输出
//   ud_cnt      - 加减可逆计数器输出（4位）
//   ud_carry    - 加减可逆计数器进位/借位输出
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

module counter (
    input              clk,            // 系统时钟
    input              rst_n,          // 复位信号，低有效
    input              en,             // 计数使能
    input              up_down,        // 加减控制，1加0减
    output reg  [3:0]  bin_cnt,        // 二进制计数器
    output             bin_carry,      // 二进制进位
    output reg  [7:0]  bcd_cnt,        // BCD计数器（两位十进制）
    output             bcd_carry,      // BCD进位
    output reg  [2:0]  mod6_cnt,       // 模6计数器
    output             mod6_carry,     // 模6进位
    output reg  [3:0]  ud_cnt,         // 加减可逆计数器
    output             ud_carry        // 加减可逆进位/借位
);

// ============================================================
// 一、计数器概述
// ============================================================
//
// 计数器是数字系统中最常用的时序逻辑电路之一，
// 功能是对时钟脉冲的个数进行计数。
//
// 计数器的分类：
//   按计数进制分：二进制计数器、十进制(BCD)计数器、模N计数器
//   按增减方向分：加计数器、减计数器、可逆计数器
//   按触发方式分：同步计数器、异步计数器
//   按编码方式分：二进制码、格雷码、独热码
//
// 计数器的应用：
//   1. 时钟分频：对高频时钟分频得到低频时钟
//   2. 时序控制：产生固定周期的控制信号
//   3. 事件计数：统计外部事件发生的次数
//   4. 地址生成：存储器地址的自动递增/递减
// ============================================================

// ============================================================
// 二、4位二进制计数器
// ============================================================
//
// 4位二进制计数器：从0计数到15，然后回到0，循环往复。
// 共有 2^4 = 16 个状态。
//
// 状态序列（加计数）：
//   0000 → 0001 → 0010 → ... → 1110 → 1111 → 0000 → ...
//
// 进位输出：
//   当计数器计到最大值（1111）且使能有效时，产生进位。
//   进位信号可以作为下一级计数器的使能信号，实现级联。
//
// 同步计数器 vs 异步计数器：
//   同步计数器：所有触发器共用同一个时钟，速度快，设计简单
//   异步计数器：低位的输出作为高位的时钟，速度慢，有毛刺
//
// 现代数字设计几乎都采用同步计数器。
// ============================================================

// 4位二进制加计数器（同步使能）
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // 复位：计数器清0
        bin_cnt <= 4'd0;
    end
    else if (en) begin
        // 使能有效时，每个时钟加1
        bin_cnt <= bin_cnt + 1'b1;
    end
    // 使能无效时，保持当前值
end

// 进位输出：当计数器计到最大值(15)且使能有效时，产生进位
// 进位脉冲宽度 = 1个时钟周期
assign bin_carry = en & (bin_cnt == 4'd15);

// 【知识点】使能信号的重要性
// 计数器一定要有使能信号（en），不能每个时钟都计数。
// 原因：
//   1. 灵活性：可以随时暂停/恢复计数
//   2. 级联方便：低位的进位作为高位的使能
//   3. 功耗优化：不计数时触发器保持，减少翻转
//
// 级联示例（两个4位计数器组成8位计数器）：
//   低位计数器：en = 1（始终使能）
//   高位计数器：en = 低位进位
//   这样低位计满15后，高位才加1，正好组成8位计数器。

// ============================================================
// 三、BCD计数器（十进制计数器）
// ============================================================
//
// BCD（Binary Coded Decimal）计数器：用二进制编码表示十进制数。
// 每位十进制数用4位二进制表示，范围0000~1001（0~9），
// 1010~1111 是无效状态。
//
// 1位BCD计数器（模10）状态序列：
//   0000 → 0001 → ... → 1001 → 0000 → ...
//   （0）    （1）   ...    （9）    （0）
//
// 多位BCD计数器：
//   每4位表示一位十进制数，低位计满9后进位，高位加1。
//   例如两位BCD计数器：从00→99→00
//
// BCD计数器的应用：
//   - 数字时钟（时、分、秒都是十进制）
//   - 数码管显示（直接输出十进制，不需要转换）
//   - 需要人眼可读的计数场合
// ============================================================

// 两位BCD计数器（00~99）
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // 复位：两位都清0
        bcd_cnt <= 8'h00;  // 高4位是十位，低4位是个位
    end
    else if (en) begin
        // 使能有效时计数
        if (bcd_cnt[3:0] == 4'd9) begin
            // 个位等于9，个位清0，检查十位
            bcd_cnt[3:0] <= 4'd0;
            if (bcd_cnt[7:4] == 4'd9) begin
                // 十位也等于9，十位也清0（计到99，回到00）
                bcd_cnt[7:4] <= 4'd0;
            end
            else begin
                // 十位不等于9，十位加1
                bcd_cnt[7:4] <= bcd_cnt[7:4] + 1'b1;
            end
        end
        else begin
            // 个位不等于9，个位加1，十位不变
            bcd_cnt[3:0] <= bcd_cnt[3:0] + 1'b1;
        end
    end
end

// BCD进位输出：两位都为9且使能有效时产生进位
assign bcd_carry = en & (bcd_cnt == 8'h99);

// 【BCD计数器 vs 二进制计数器】
//
// | 特性         | BCD计数器        | 二进制计数器      |
// |-------------+-----------------+-----------------|
// | 编码方式     | 每位十进制用4位  | 纯二进制          |
// | 4位状态数    | 10（0~9）        | 16（0~15）        |
// | 状态利用率   | 低（62.5%）      | 高（100%）        |
// | 显示接口     | 直接接7段译码器   | 需要二进制转BCD    |
// | 适用场景     | 数字显示、人机交互 | 内部运算、地址计数 |
//
// 设计选择：
//   - 内部运算用二进制计数器（效率高）
//   - 给人看的显示用BCD计数器（方便）

// ============================================================
// 四、模N计数器
// ============================================================
//
// 模N计数器：计数到N-1后回到0，共有N个状态。
// 模数（Modulus）= 状态数 = N
//
// 例如：
//   模6计数器：0, 1, 2, 3, 4, 5, 0, 1, ...
//   模10计数器：0~9（就是BCD计数器）
//   模60计数器：0~59（秒、分的计数）
//
// 设计方法：
//   1. 确定需要的位数：n = ceil(log2(N))
//   2. 计数器从0开始加1
//   3. 当计到 N-1 时，下一个时钟回到0
//
// 本模块实现一个模6计数器（0~5）。
// ============================================================

// 模6计数器（0,1,2,3,4,5,0,1,...）
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        mod6_cnt <= 3'd0;
    end
    else if (en) begin
        if (mod6_cnt == 3'd5) begin
            // 计到最大值5，回到0
            mod6_cnt <= 3'd0;
        end
        else begin
            // 未到最大值，加1
            mod6_cnt <= mod6_cnt + 1'b1;
        end
    end
end

// 模6进位输出：计到5且使能有效时产生进位
assign mod6_carry = en & (mod6_cnt == 3'd5);


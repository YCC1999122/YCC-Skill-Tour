// 【级联示例：数字时钟】
// 秒计数器：模60（00~59秒）
// 分计数器：模60（00~59分），使能 = 秒进位
// 时计数器：模24（00~23时），使能 = 分进位
// 这样就组成了一个完整的24小时制数字时钟。

// ============================================================
// 五、加减可逆计数器
// ============================================================
//
// 加减可逆计数器：既可以加计数，也可以减计数，
// 通过一个控制信号来选择计数方向。
//
// 加计数（up_down=1）：0→1→2→...→MAX→0→...
// 减计数（up_down=0）：MAX→MAX-1→...→1→0→MAX→...
//
// 进位/借位输出：
//   - 加计数时：计到最大值且使能有效 → 进位（carry）
//   - 减计数时：计到最小值(0)且使能有效 → 借位（borrow）
//   本模块用同一个输出表示，加计数时为进位，减计数时为借位。
// ============================================================

// 4位加减可逆计数器
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        ud_cnt <= 4'd0;
    end
    else if (en) begin
        if (up_down) begin
            // up_down=1：加计数
            if (ud_cnt == 4'd15) begin
                ud_cnt <= 4'd0;       // 计满，回到0
            end
            else begin
                ud_cnt <= ud_cnt + 1'b1;
            end
        end
        else begin
            // up_down=0：减计数
            if (ud_cnt == 4'd0) begin
                ud_cnt <= 4'd15;      // 减到0，回到最大值
            end
            else begin
                ud_cnt <= ud_cnt - 1'b1;
            end
        end
    end
end

// 进位/借位输出
// 加计数时：计到最大值 → 进位
// 减计数时：计到最小值 → 借位
assign ud_carry = en & (
    (up_down & (ud_cnt == 4'd15)) |   // 加计数进位
    (~up_down & (ud_cnt == 4'd0))     // 减计数借位
);

// 【可逆计数器的应用】
//   1. 位置控制：步进电机的正反转计数
//   2. 频率合成：加减计数实现分数分频
//   3. 上下限控制：达到上限减、达到下限加
//   4. 流水线深度控制：写入加、读出减

// ============================================================
// 六、各种计数器对比
// ============================================================
//
// | 计数器类型     | 状态数    | 特点                 | 典型应用         |
// |---------------+----------+---------------------+-----------------|
// | 二进制计数器   | 2^N      | 状态利用率最高        | 地址、通用计数    |
// | BCD计数器      | 10^M     | 十进制格式，方便显示   | 数字时钟、显示    |
// | 模N计数器      | N        | 任意模数，灵活        | 分频、特定周期    |
// | 加减可逆计数器 | 2^N      | 可加可减             | 位置控制、深度控制 |
//
// 设计注意事项：
//   1. 一定要加使能信号 en，方便级联和控制
//   2. 同步设计：所有触发器用同一个时钟
//   3. 复位设计：确定用同步复位还是异步复位
//   4. 溢出处理：明确计满/减到0后的行为
//   5. 毛刺问题：组合逻辑译码输出可能有毛刺，需要时用寄存器打拍
// ============================================================

endmodule

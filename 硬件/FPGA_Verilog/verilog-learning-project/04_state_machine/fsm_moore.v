// ============================================================
// 模块名：fsm_moore
// 功能描述：Moore型状态机设计示例
//           演示 Moore 型与 Mealy 型的区别、
//           使用三段式写法实现 1101 序列检测器
// 输入端口：
//   clk      - 系统时钟，上升沿触发
//   rst_n    - 复位信号，低有效，异步复位
//   din      - 串行数据输入，1位
// 输出端口：
//   detect   - 检测到1101序列时输出高电平（Moore输出）
//              输出仅与当前状态有关，与输入无关
//   state_oh - 当前状态（独热码输出，调试用）
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

// ============================================================
// 【Moore 型状态机 vs Mealy 型状态机】
//
// Moore 型状态机的特点：
//   输出仅取决于当前状态，与当前输入无关
//   输出 = F(当前状态)
//
// Mealy 型状态机的特点：
//   输出取决于当前状态和当前输入
//   输出 = F(当前状态, 当前输入)
//
// 对比：
// ┌─────────────┬──────────────────┬──────────────────┐
// │    特性     │      Mealy       │      Moore       │
// ├─────────────┼──────────────────┼──────────────────┤
// │ 输出决定因素 │ 当前状态 + 输入   │ 仅当前状态        │
// │ 状态数      │ 较少             │ 较多             │
// │ 输出响应    │ 输入变化立即响应  │ 时钟沿才变化      │
// │ 输出毛刺    │ 可能有           │ 无（寄存输出）    │
// │ 设计复杂度  │ 稍高             │ 较直观           │
// └─────────────┴──────────────────┴──────────────────┘
//
// 本模块实现 Moore 型的 1101 序列检测器：
//   当串行输入出现 "1101" 序列时，输出一个时钟周期的高电平
//   由于是 Moore 型，输出在进入检测成功状态后的时钟沿才拉高
// ============================================================

module fsm_moore (
    input            clk,          // 系统时钟
    input            rst_n,        // 复位信号，低有效
    input            din,          // 串行数据输入
    output reg       detect,       // 检测到1101序列（Moore输出）
    output reg [4:0] state_oh      // 当前状态输出（独热码，调试用）
);

// ============================================================
// 一、状态定义（独热码编码）
// ============================================================
//
// 检测 1101 序列，共需要 5 个状态：
//   IDLE : 初始状态，还没收到有效位
//   S1   : 已收到 '1'
//   S2   : 已收到 '11'
//   S3   : 已收到 '110'
//   S4   : 已收到 '1101'（检测成功状态）
//
// 使用独热码（One-Hot）编码：
//   - 5个状态需要5位，每个状态只有一位为1
//   - FPGA中触发器资源丰富，独热码译码简单、速度快
//   - 状态转移时只有一位翻转（从旧状态位到新状态位）
// ============================================================

// 独热码状态定义
// 每个状态对应一位，只有一位是 1
localparam IDLE = 5'b00001;  // 初始状态
localparam S1   = 5'b00010;  // 收到 '1'
localparam S2   = 5'b00100;  // 收到 '11'
localparam S3   = 5'b01000;  // 收到 '110'
localparam S4   = 5'b10000;  // 收到 '1101'，检测成功

// ============================================================
// 二、三段式状态机
// ============================================================
// 三段式结构：
//   第一段：时序逻辑 - 现态寄存器（current_state）
//   第二段：组合逻辑 - 次态逻辑（next_state）
//   第三段：时序逻辑 - 输出寄存器（Moore 输出）
//
// Moore 型的输出只取决于当前状态，所以输出逻辑
// 可以用组合逻辑或时序逻辑实现。
// 本示例使用时序逻辑（寄存器输出），消除毛刺。
// ============================================================

// ------------------------------------------------------------
// 第一段：时序逻辑，现态寄存器
// 每个时钟上升沿，将次态打入现态寄存器
// ------------------------------------------------------------

reg [4:0] current_state;  // 当前状态（独热码，5位）
reg [4:0] next_state;     // 下一个状态（组合逻辑）

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // 复位时进入初始状态
        current_state <= IDLE;
    end
    else begin
        current_state <= next_state;
    end
end

// ------------------------------------------------------------
// 第二段：组合逻辑，次态转移
// 根据当前状态和输入 din，计算下一个状态
// ------------------------------------------------------------

always @(*) begin
    // 默认值：保持当前状态（防止生成 latch）
    next_state = current_state;

    case (current_state)
        IDLE: begin  // 初始状态
            if (din == 1'b1) begin
                next_state = S1;    // 收到 '1'，进入 S1
            end
            else begin
                next_state = IDLE;  // 收到 '0'，保持 IDLE
            end
        end

        S1: begin  // 已收到 '1'
            if (din == 1'b1) begin
                next_state = S2;    // 收到 '1'，进入 S2（"11"）
            end
            else begin
                next_state = IDLE;  // 收到 '0'，序列中断，回到 IDLE
            end
        end

        S2: begin  // 已收到 '11'
            if (din == 1'b0) begin
                next_state = S3;    // 收到 '0'，进入 S3（"110"）
            end
            else begin
                next_state = S2;    // 收到 '1'，保持 S2（连续的1还是"11"）
            end
        end

        S3: begin  // 已收到 '110'
            if (din == 1'b1) begin
                next_state = S4;    // 收到 '1'，进入 S4（"1101"，检测成功）
            end
            else begin
                next_state = IDLE;  // 收到 '0'，序列中断，回到 IDLE
            end
        end

        S4: begin  // 已收到 '1101'（检测成功状态）
            // Moore 型特点：进入此状态后 detect 才变高
            // 检测成功后，判断下一个输入以决定下一个状态
            if (din == 1'b1) begin
                // 收到 '1'，因为可以重叠检测
                // "1101" 的最后一个 '1' 可作为新序列的第一个 '1'
                // 但新序列需要 "1101"，所以此时只有一个 '1'
                next_state = S1;
            end
            else begin
                next_state = IDLE;  // 收到 '0'，回到初始状态
            end
        end

        default: begin
            next_state = IDLE;      // 未定义状态，回到初始状态
        end
    endcase
end

// ------------------------------------------------------------
// 第三段：时序逻辑，Moore 输出
// Moore 型输出仅取决于当前状态
// 使用时序逻辑寄存输出，消除毛刺
//
// 注意：因为是 Moore 型，detect 信号只在 S4 状态时为高
//       输出变化发生在进入 S4 状态的时钟沿之后
//       比 Mealy 型晚一个时钟周期
// ------------------------------------------------------------

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        detect <= 1'b0;
    end
    else begin
        // Moore 输出：仅由当前状态决定
        // 只有在 S4 状态时，detect 才为高
        if (current_state == S4) begin
            detect <= 1'b1;
        end
        else begin
            detect <= 1'b0;
        end
    end
end

// ------------------------------------------------------------
// 状态输出（调试用，独热码）
// 将当前状态以独热码形式输出，便于仿真观察
// ------------------------------------------------------------

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        state_oh <= 5'b00001;  // 复位时输出 IDLE 状态
    end
    else begin
        state_oh <= current_state;
    end
end

// ============================================================
// 三、序列检测的重叠与非重叠
// ============================================================
//
// 序列检测分为两种模式：
//
// 1. 重叠检测（Overlapping）
//    - 检测到序列后，序列的末尾可以作为下一个序列的开头
//    - 例如：输入 "1101101"，非重叠检测只找到1个
//            重叠检测可以找到2个（位置0和位置4）
//    - 本设计采用重叠检测
//
// 2. 非重叠检测（Non-overlapping）
//    - 检测到序列后，从头开始寻找下一个序列
//    - 例如：输入 "1101101"，只检测到1个
//    - 如需非重叠，S4 状态收到 '1' 时应跳到 S1 而非 S2
//      （本设计中 S4->S1 实际就是重叠的一种实现）
//
// 本设计状态转移说明（重叠模式）：
//   输入序列：1 1 0 1 1 0 1
//   状态变化：IDLE -> S1 -> S2 -> S3 -> S4 -> S1 -> S2 -> S3 -> S4
//   detect:   0     0    0    0    1    0    0    0    1
//   检测到2次 "1101"
// ============================================================

// ============================================================
// 四、Moore 型状态机的特点总结
// ============================================================
//
// 优点：
// 1. 输出仅取决于状态，与输入无关，逻辑清晰
// 2. 输出稳定，不会因为输入的毛刺而产生输出毛刺
// 3. 容易设计和验证，状态图更直观
// 4. 输出可以直接寄存，时序性能好
//
// 缺点：
// 1. 状态数通常比 Mealy 型多（需要更多触发器）
// 2. 输出响应比 Mealy 型晚一个时钟周期
// 3. 对于相同功能，Moore 型可能需要更多状态
//
// 应用场景：
// - 计数器（可以看作简单的 Moore 机）
// - 交通灯控制器
// - 各种控制状态机
// - 对输出稳定性要求高的场合
//
// 【设计建议】
// 1. 大多数数字系统中，Moore 型更常用，因为输出稳定
// 2. 如果需要快速响应输入，选择 Mealy 型
// 3. FPGA 中推荐独热码 + 三段式写法
// 4. 状态编码可以用 parameter/localparam 定义，方便修改
// 5. 始终考虑未使用状态的处理（default 分支）
// ============================================================

endmodule

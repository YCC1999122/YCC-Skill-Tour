// 模块名：fsm_mealy
// 功能描述：Mealy型状态机设计示例
//           演示状态机基本概念、一段式/两段式/三段式写法、
//           状态编码方式（二进制/独热码/格雷码）
//           实现一个简单的"101"序列检测器（Mealy型）
// 输入端口：
//   clk      - 系统时钟，上升沿触发
//   rst_n    - 复位信号，低有效，异步复位
//   din      - 串行数据输入，1位
// 输出端口：
//   detect_1shot  - 检测到101序列时输出一个脉冲（Mealy输出）
//   state_bin     - 当前状态（二进制编码输出，调试用）
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

// ============================================================
// 【状态机基本概念】
//
// 有限状态机（Finite State Machine, FSM）是数字电路中
// 描述时序逻辑的重要方法，由以下要素组成：
//
// 1. 状态（State）：系统当前所处的模式或条件
// 2. 输入（Input）：影响状态转移的外部信号
// 3. 输出（Output）：系统的响应信号
// 4. 状态转移函数：根据当前状态和输入决定下一个状态
// 5. 输出函数：根据当前状态（和输入）决定输出
//
// Mealy型状态机 vs Moore型状态机：
//
// Mealy型：输出不仅取决于当前状态，还取决于当前输入
//   - 输出 = F(当前状态, 当前输入)
//   - 输入变化时，输出可能立即变化（组合逻辑）
//   - 状态数通常较少
//
// Moore型：输出仅取决于当前状态，与当前输入无关
//   - 输出 = F(当前状态)
//   - 输出只在时钟沿变化时才改变
//   - 状态数通常较多
//
// 本模块实现 Mealy 型的 101 序列检测器：
//   当串行输入出现 "101" 序列时，输出一个时钟周期的高脉冲
// ============================================================

module fsm_mealy (
    input            clk,          // 系统时钟
    input            rst_n,        // 复位信号，低有效
    input            din,          // 串行数据输入
    output reg       detect_1shot, // 检测到101序列的脉冲输出
    output reg [2:0] state_bin     // 当前状态输出（二进制编码）
);

// ============================================================
// 一、状态定义与状态编码
// ============================================================
//
// 状态编码方式有三种：
//
// 1. 二进制编码（Binary Encoding）
//    - 用最少的位数表示所有状态
//    - N个状态需要 log2(N) 位
//    - 优点：占用触发器少
//    - 缺点：状态转移时可能多位同时翻转，容易产生毛刺
//    - 适用：状态数多、对速度要求不高的场合
//
// 2. 独热码（One-Hot Encoding）
//    - 每个状态用一位表示，同一时刻只有一位为1
//    - N个状态需要 N 位
//    - 优点：状态译码简单、速度快、不会有多位翻转的毛刺
//    - 缺点：占用触发器多
//    - 适用：FPGA中资源丰富、状态数不多的场合（FPGA推荐）
//
// 3. 格雷码（Gray Code Encoding）
//    - 相邻状态之间只有一位不同
//    - N个状态需要 log2(N) 位
//    - 优点：状态转移时只有一位翻转，减少毛刺
//    - 缺点：译码比独热码复杂
//    - 适用：状态机输出作为时钟或异步信号的场合
//
// 本示例使用二进制编码，同时在注释中给出其他编码方式

// ------------------------------------------------------------
// 状态定义（使用 localparam，局部参数，不可被外部修改）
// 共4个状态：
//   S0 : 初始状态，等待第一个 '1'
//   S1 : 已收到 '1'，等待 '0'
//   S2 : 已收到 '10'，等待 '1'
//   S3 : 已收到 '101'，回到 S1（因为可以重叠检测）
// ------------------------------------------------------------

// 方式1：二进制编码（Binary）
localparam S0 = 2'b00;  // 初始状态
localparam S1 = 2'b01;  // 收到 '1'
localparam S2 = 2'b10;  // 收到 '10'
localparam S3 = 2'b11;  // 收到 '101'（这里仅作演示，实际可省）

/*
// 方式2：独热码（One-Hot）
// 4个状态需要4位，每次只有一位为1
localparam S0 = 4'b0001;
localparam S1 = 4'b0010;
localparam S2 = 4'b0100;
localparam S3 = 4'b1000;

// 方式3：格雷码（Gray Code）
// 相邻状态只有一位不同
localparam S0 = 2'b00;
localparam S1 = 2'b01;
localparam S2 = 2'b11;  // 注意：S1(01)->S2(11) 只有一位变
localparam S3 = 2'b10;  // 注意：S2(11)->S3(10) 只有一位变
*/

// ============================================================
// 二、状态机的写法
// ============================================================
//
// 状态机通常有三种写法：一段式、两段式、三段式
//
// 1. 一段式（One always block）
//    - 整个状态机写在一个 always 块中
//    - 状态寄存器和组合逻辑混在一起
//    - 优点：代码简洁
//    - 缺点：不易维护，容易产生 latch，不推荐
//
// 2. 两段式（Two always blocks）
//    - 第一个 always 块：时序逻辑，描述状态寄存器
//    - 第二个 always 块：组合逻辑，描述状态转移和输出
//    - 优点：结构清晰
//    - 缺点：输出是组合逻辑，可能有毛刺
//
// 3. 三段式（Three always blocks）
//    - 第一个 always 块：时序逻辑，描述状态寄存器（现态）
//    - 第二个 always 块：组合逻辑，描述状态转移逻辑（次态）
//    - 第三个 always 块：时序逻辑，描述输出寄存器
//    - 优点：结构最清晰，输出寄存后无毛刺，时序好
//    - 缺点：代码量稍多
//    - 【推荐写法】：在实际工程中推荐使用三段式
//
// 本模块使用【三段式】写法，这是工业界最推荐的方式
// ============================================================

// ------------------------------------------------------------
// 第一段：时序逻辑，状态寄存器（现态 current_state）
// 功能：在时钟上升沿更新当前状态
// ------------------------------------------------------------

reg [1:0] current_state;  // 当前状态寄存器（二进制编码，2位）
reg [1:0] next_state;     // 下一个状态（组合逻辑输出）

// 状态寄存器：每个时钟上升沿，将 next_state 打入 current_state
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // 复位时进入初始状态 S0
        current_state <= S0;
    end
    else begin
        current_state <= next_state;
    end
end

// ------------------------------------------------------------
// 第二段：组合逻辑，状态转移逻辑（次态 next_state）
// 功能：根据当前状态和输入，计算下一个状态
// 注意：组合逻辑使用阻塞赋值 =，敏感列表用 @(*)
// ------------------------------------------------------------

always @(*) begin
    // 默认值：保持当前状态（避免生成 latch）
    // 组合逻辑中必须确保所有分支都给 next_state 赋值
    // 设置默认值是一个好习惯
    next_state = current_state;

    case (current_state)
        S0: begin  // 初始状态，等待第一个 '1'
            if (din == 1'b1) begin
                next_state = S1;  // 收到 '1'，进入 S1
            end
            else begin
                next_state = S0;  // 收到 '0'，保持 S0
            end
        end

        S1: begin  // 已收到 '1'，等待 '0'
            if (din == 1'b0) begin
                next_state = S2;  // 收到 '0'，进入 S2（即已收"10"）
            end
            else begin
                next_state = S1;  // 收到 '1'，保持 S1（连续的1还是"1"）
            end
        end

        S2: begin  // 已收到 '10'，等待 '1'
            if (din == 1'b1) begin
                // 收到 '1'，检测到 "101" 序列
                // Mealy型：输出会立即变化（见第三段）
                // 进入 S1，因为可以重叠检测（如 "10101" 中有两个101）
                // 最后一个 '1' 可以作为下一个序列的起始
                next_state = S1;
            end
            else begin
                next_state = S0;  // 收到 '0'，序列中断，回到 S0
            end
        end

        default: begin
            next_state = S0;  // 安全起见，默认回到初始状态
        end
    endcase
end

// ------------------------------------------------------------
// 第三段：输出逻辑
// 对于 Mealy 型状态机，输出取决于当前状态和当前输入
// 这里输出使用寄存器（时序逻辑），避免组合逻辑毛刺
// 注意：寄存后的输出会延迟一个时钟周期
// ------------------------------------------------------------

// Mealy 型输出：输出 = F(当前状态, 当前输入)
// 当 current_state == S2 且 din == 1 时，表示检测到 101
// 使用时序逻辑寄存输出，消除毛刺
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        detect_1shot <= 1'b0;
    end
    else begin
        // Mealy 输出：同时取决于当前状态和输入
        // 在 S2 状态下，如果输入为 1，则检测成功
        if (current_state == S2 && din == 1'b1) begin
            detect_1shot <= 1'b1;
        end
        else begin
            detect_1shot <= 1'b0;
        end
    end
end

// ------------------------------------------------------------
// 状态输出（调试用，二进制编码）
// 将当前状态输出，便于在仿真中观察
// ------------------------------------------------------------

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        state_bin <= 3'd0;
    end
    else begin
        // 扩展到3位输出，方便观察
        state_bin <= {1'b0, current_state};
    end
end

// ============================================================
// 三、Mealy 型状态机的特点总结
// ============================================================
//
// 优点：
// 1. 状态数通常比 Moore 型少
// 2. 响应速度快，输入变化后输出立即变化（组合输出时）
// 3. 适合需要快速响应输入变化的场景
//
// 缺点：
// 1. 输出可能有毛刺（因为输入直接影响输出）
// 2. 输出与输入同步变化，时序分析稍复杂
// 3. 设计时需要考虑输入的异步特性
//
// 应用场景：
// - 序列检测器
// - 总线控制器
// - 需要快速响应输入的控制系统
//
// 【设计注意事项】
// 1. 一定要给所有状态定义转移，使用 default 覆盖未定义状态
// 2. 组合逻辑中设置默认值，避免生成 latch
// 3. 输出建议用寄存器打拍，消除毛刺
// 4. 状态编码根据实际需求选择（FPGA 推荐独热码）
// 5. 复位时一定要给状态寄存器赋初值
// ============================================================

endmodule

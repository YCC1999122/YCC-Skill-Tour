// ============================================================
// 模块名：fsm_traffic_light
// 功能描述：交通灯控制器状态机（Moore型综合实例）
//           演示多状态转移、定时切换、状态机综合应用
//           东西方向和南北方向红绿灯交替切换
// 输入端口：
//   clk        - 系统时钟，假设 50MHz
//   rst_n      - 复位信号，低有效，异步复位
//   enable     - 使能信号，高电平有效
// 输出端口：
//   led_ew     - 东西方向灯，3位{红,黄,绿}
//   led_ns     - 南北方向灯，3位{红,黄,绿}
//   state_out  - 当前状态输出（独热码，调试用）
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

// ============================================================
// 【交通灯控制器设计说明】
//
// 这是一个典型的 Moore 型状态机应用实例。
// 输出（灯的状态）仅取决于当前状态。
//
// 状态转移图：
//
//   ┌──────────┐   时间到   ┌──────────┐
//   │ S0:      │──────────>│ S1:      │
//   │ 东西绿灯  │           │ 东西黄灯  │
//   │ 南北红灯  │           │ 南北红灯  │
//   └──────────┘           └────┬─────┘
//        Λ                      │ 时间到
//        │ 时间到                V
//   ┌────┴─────┐           ┌──────────┐
//   │ S3:      │<──────────│ S2:      │
//   │ 东西黄灯  │   时间到   │ 东西红灯  │
//   │ 南北红灯  │           │ 南北绿灯  │
//   └──────────┘           └──────────┘
//
// 状态说明：
//   S0：东西绿灯、南北红灯（通行时间最长）
//   S1：东西黄灯、南北红灯（警告时间，较短）
//   S2：东西红灯、南北绿灯（通行时间最长）
//   S3：东西红灯、南北黄灯（警告时间，较短）
//
// 时间分配（假设50MHz时钟）：
//   绿灯：3秒  = 150,000,000 个时钟周期
//   黄灯：0.5秒 = 25,000,000 个时钟周期
//
// 为了仿真方便，本设计使用可配置的计数器参数
// ============================================================

module fsm_traffic_light (
    input            clk,         // 系统时钟，50MHz
    input            rst_n,       // 复位信号，低有效
    input            enable,      // 使能信号
    output reg [2:0] led_ew,      // 东西方向灯 {红,黄,绿}
    output reg [2:0] led_ns,      // 南北方向灯 {红,黄,绿}
    output reg [3:0] state_out    // 当前状态输出（独热码）
);

// ============================================================
// 一、参数定义
// ============================================================
//
// 使用 parameter 定义时间参数，方便修改
// 假设时钟频率为 50MHz，周期为 20ns
// 绿灯时间 3 秒 = 3 / 20ns = 150,000,000 个周期
// 黄灯时间 0.5 秒 = 0.5 / 20ns = 25,000,000 个周期
//
// 为了仿真方便，这里使用较小的数值
// 实际使用时根据需要修改
// ============================================================

parameter GREEN_TIME = 26'd300;   // 绿灯持续时钟数（仿真用小值）
parameter YELLOW_TIME = 26'd50;   // 黄灯持续时钟数（仿真用小值）

// ============================================================
// 二、状态定义（独热码）
// ============================================================
//
// 4个状态，使用独热码编码
// 独热码在 FPGA 中综合效果好，译码简单
// ============================================================

localparam S0 = 4'b0001;  // 东西绿灯，南北红灯
localparam S1 = 4'b0010;  // 东西黄灯，南北红灯
localparam S2 = 4'b0100;  // 东西红灯，南北绿灯
localparam S3 = 4'b1000;  // 东西红灯，南北黄灯

// ============================================================
// 三、三段式状态机 + 计时器
// ============================================================
//
// 交通灯状态机的核心是：
//   每个状态停留一段时间，时间到后跳转到下一个状态
//
// 实现方式：
//   1. 用一个计数器记录当前状态已经持续了多少个时钟周期
//   2. 进入新状态时，计数器清零
//   3. 当计数器达到该状态的设定时间时，触发状态转移
//
// 这是一个 Moore 型状态机：输出完全由当前状态决定
// ============================================================

// ------------------------------------------------------------
// 第一段：时序逻辑，现态寄存器
// ------------------------------------------------------------

reg [3:0] current_state;  // 当前状态（独热码）
reg [3:0] next_state;     // 下一个状态（组合逻辑）

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        current_state <= S0;  // 复位后从 S0 开始
    end
    else begin
        current_state <= next_state;
    end
end

// ------------------------------------------------------------
// 计时器模块
// 记录当前状态的持续时间
// 状态变化时计数器清零
// ------------------------------------------------------------

reg [25:0] timer;        // 计时器（最大支持约 6700万，即 1.3秒@50MHz）
wire time_up;             // 时间到标志

// 计时器：每个时钟周期加1
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        timer <= 26'd0;
    end
    else if (!enable) begin
        // 使能无效时，计时器停止
        timer <= timer;
    end
    else if (current_state != next_state) begin
        // 状态即将变化，下一个周期进入新状态
        // 计数器清零（注意：这里用 current_state != next_state
        // 来检测状态即将变化，实际工程中可以用更明确的方式）
        timer <= 26'd0;
    end
    else if (time_up) begin
        // 时间到后保持最大值（不再继续计数）
        timer <= timer;
    end
    else begin
        // 正常计数
        timer <= timer + 1'b1;
    end
end

// 时间到判断：根据当前状态比较不同的时间阈值
// 这是组合逻辑
assign time_up = (current_state == S0) ? (timer >= GREEN_TIME)  :
                 (current_state == S1) ? (timer >= YELLOW_TIME) :
                 (current_state == S2) ? (timer >= GREEN_TIME)  :
                 (current_state == S3) ? (timer >= YELLOW_TIME) :
                 1'b0;

// ------------------------------------------------------------
// 第二段：组合逻辑，次态转移
// 根据当前状态和 time_up 信号决定下一个状态
// ------------------------------------------------------------

always @(*) begin
    // 默认值：保持当前状态
    next_state = current_state;

    if (!enable) begin
        // 使能无效时，保持当前状态
        next_state = current_state;
    end
    else begin
        case (current_state)
            S0: begin  // 东西绿灯、南北红灯
                if (time_up) begin
                    next_state = S1;  // 绿灯时间到，转黄灯
                end
            end

            S1: begin  // 东西黄灯、南北红灯
                if (time_up) begin
                    next_state = S2;  // 黄灯时间到，转南北绿灯
                end
            end

            S2: begin  // 东西红灯、南北绿灯
                if (time_up) begin
                    next_state = S3;  // 绿灯时间到，转黄灯
                end
            end

            S3: begin  // 东西红灯、南北黄灯
                if (time_up) begin
                    next_state = S0;  // 黄灯时间到，回到 S0
                end
            end

            default: begin
                next_state = S0;  // 未定义状态，回到 S0
            end
        endcase
    end
end

// ------------------------------------------------------------
// 第三段：时序逻辑，Moore 输出
// 输出完全由当前状态决定
//
// 灯的编码：{红, 黄, 绿}
//   3'b100 = 红灯亮
//   3'b010 = 黄灯亮
//   3'b001 = 绿灯亮
// ------------------------------------------------------------

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // 复位状态：东西红灯、南北红灯（安全状态）
        led_ew <= 3'b100;
        led_ns <= 3'b100;
    end
    else begin
        case (current_state)
            S0: begin
                // 东西绿灯，南北红灯
                led_ew <= 3'b001;  // 绿
                led_ns <= 3'b100;  // 红
            end

            S1: begin
                // 东西黄灯，南北红灯
                led_ew <= 3'b010;  // 黄
                led_ns <= 3'b100;  // 红
            end

            S2: begin
                // 东西红灯，南北绿灯
                led_ew <= 3'b100;  // 红
                led_ns <= 3'b001;  // 绿
            end

            S3: begin
                // 东西红灯，南北黄灯
                led_ew <= 3'b100;  // 红
                led_ns <= 3'b010;  // 黄
            end

            default: begin
                // 安全默认：全红
                led_ew <= 3'b100;
                led_ns <= 3'b100;
            end
        endcase
    end
end

// ------------------------------------------------------------
// 状态输出（调试用）
// ------------------------------------------------------------

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        state_out <= S0;
    end
    else begin
        state_out <= current_state;
    end
end

// ============================================================
// 四、状态机设计进阶知识
// ============================================================
//
// 4.1 安全状态机设计
//     - 状态机可能因为干扰进入未定义状态
//     - 必须在 case 语句中加 default 分支
//     - default 通常跳转到初始状态或安全状态
//     - 本设计 default 跳转到 S0（且输出全红作为安全措施）
//
// 4.2 状态编码的选择
//     - 二进制编码：节省触发器，适合状态数很多的情况
//     - 独热码：速度快、译码简单，FPGA 推荐
//     - 格雷码：状态转移一位翻转，适合异步场合
//     - FPGA 中一般使用独热码，因为触发器资源丰富
//
// 4.3 状态机的优化
//     - 状态数精简：合并功能相似的状态
//     - 输出优化：输出寄存器化，改善时序
//     - 复位策略：异步复位还是同步复位
//
// 4.4 验证要点
//     - 检查所有状态是否都能到达
//     - 检查所有状态的转移是否正确
//     - 检查复位后是否进入正确状态
//     - 检查未定义状态的处理（default）
//     - 检查输出是否有毛刺
//
// 4.5 常见错误
//     - 组合逻辑中遗漏赋值，生成 latch
//     - 敏感列表不完整（应使用 @(*)）
//     - 状态编码冲突或遗漏
//     - 输出与时序要求不符
//     - 忘记加 default 分支
// ============================================================


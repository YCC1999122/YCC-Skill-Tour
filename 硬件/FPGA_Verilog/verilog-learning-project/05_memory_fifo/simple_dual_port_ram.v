// ============================================================
// 模块名：simple_dual_port_ram
// 功能描述：简单双端口RAM设计示例
//           演示读写独立端口、双时钟、与真双端口的区别
//           一个写端口 + 一个独立的读端口
// 输入端口：
//   wr_clk   - 写端口时钟
//   rd_clk   - 读端口时钟
//   we       - 写使能，高有效
//   wr_en    - 写端口使能
//   rd_en    - 读端口使能
//   wr_addr  - 写地址
//   rd_addr  - 读地址
//   din      - 写入数据
// 输出端口：
//   dout     - 读出数据
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

// ============================================================
// 【双端口 RAM 分类】
//
// 双端口 RAM 有两个端口，可以同时进行读写操作。
// 分为两类：
//
// 1. 简单双端口 RAM（Simple Dual Port RAM, SDP）
//    - 端口A：只写（Write-only）
//    - 端口B：只读（Read-only）
//    - 读写可以同时进行，互不干扰
//    - 两个端口可以使用不同的时钟（异步双时钟）
//    - FPGA 中 BRAM 都支持简单双端口模式
//
// 2. 真双端口 RAM（True Dual Port RAM, TDP）
//    - 端口A：可读可写
//    - 端口B：可读可写
//    - 两个端口完全独立，都可以读写
//    - 两个端口可以使用不同的时钟
//    - 需要处理两个端口同时写同一地址的冲突
//    - 资源占用比简单双端口多
//
// 对比：
// ┌──────────┬──────────────┬──────────────┐
// │   特性   │  简单双端口   │   真双端口    │
// ├──────────┼──────────────┼──────────────┤
// │ 端口A    │ 只写          │ 可读可写      │
// │ 端口B    │ 只读          │ 可读可写      │
// │ 资源占用  │ 较少          │ 较多          │
// │ 冲突处理  │ 无冲突        │ 需要处理写冲突│
// │ 应用场景  │ FIFO、缓冲    │ 双CPU共享内存  │
// └──────────┴──────────────┴──────────────┘
//
// 本模块实现简单双端口 RAM，支持双时钟
// ============================================================

module simple_dual_port_ram #(
    // ============================================================
    // 参数定义
    // ============================================================
    parameter DATA_WIDTH = 8,      // 数据位宽，默认8位
    parameter ADDR_WIDTH = 4,      // 地址位宽，默认4位
    parameter MEM_DEPTH  = 16,     // 存储深度，默认16个单元
    parameter READ_DELAY = 1       // 读延迟（拍数），默认1拍
                                   // 1=标准BRAM延迟，2=输出寄存
)(
    // 写端口
    input                         wr_clk,    // 写时钟
    input                         we,        // 写使能
    input                         wr_en,     // 写端口使能
    input       [ADDR_WIDTH-1:0]  wr_addr,   // 写地址
    input       [DATA_WIDTH-1:0]  din,       // 写入数据

    // 读端口
    input                         rd_clk,    // 读时钟
    input                         rd_en,     // 读端口使能
    input       [ADDR_WIDTH-1:0]  rd_addr,   // 读地址
    output reg  [DATA_WIDTH-1:0]  dout       // 读出数据
);

// ============================================================
// 一、存储器数组定义
// ============================================================
//
// 与单端口 RAM 一样，用二维数组描述存储体
// 虽然有两个端口，但底层是同一个存储体
// ============================================================

reg [DATA_WIDTH-1:0] mem [MEM_DEPTH-1:0];

// ============================================================
// 二、写端口（写操作）
// ============================================================
//
// 写端口使用 wr_clk 时钟
// 只有在 we 和 wr_en 同时有效时才写入
//
// 写时序：
//   时钟上升沿采样 wr_addr、din、we、wr_en
//   如果写使能有效，则将数据写入指定地址
// ============================================================

// 写操作：在 wr_clk 上升沿执行
always @(posedge wr_clk) begin
    if (wr_en && we) begin
        mem[wr_addr] <= din;
    end
end

// ============================================================
// 三、读端口（读操作）
// ============================================================
//
// 读端口使用 rd_clk 时钟（可以与 wr_clk 不同）
// 读延迟由 READ_DELAY 参数决定
//
// 读时序（READ_DELAY = 1）：
//   rd_clk:   ┌──┐  ┌──┐  ┌──┐
//             │  │  │  │  │  │
//           ──┘  └──┘  └──┘  └──
//   rd_addr:  A0     A1     A2
//   dout:           D0     D1
//                   （延迟1拍）
//
// 当读写使用不同时钟时，就是异步双端口 RAM
// 异步双端口 RAM 常用于跨时钟域的数据传输
// （如异步 FIFO 的存储体就是异步双端口 RAM）
// ============================================================

// ------------------------------------------------------------
// 生成读延迟逻辑
// 根据 READ_DELAY 参数生成不同的读延迟
// 使用 generate 块，可以根据参数条件生成不同的电路
// ------------------------------------------------------------

generate
    if (READ_DELAY == 0) begin : gen_async_read
        // 异步读（组合逻辑输出）
        // 地址变化后立即输出数据
        // 注意：异步读只能用分布式 RAM 实现
        // 不适合 BRAM
        assign dout = mem[rd_addr];
    end
    else if (READ_DELAY == 1) begin : gen_sync_read_1
        // 同步读，延迟 1 拍
        // 标准 BRAM 的读延迟
        always @(posedge rd_clk) begin
            if (rd_en) begin
                dout <= mem[rd_addr];
            end
            // else 保持原值
        end
    end
    else begin : gen_sync_read_n
        // 同步读，延迟 N 拍
        // 多级寄存器输出，用于改善时序
        // 第一级：RAM 输出
        // 第二级及以后：输出寄存器流水线

        // 定义中间寄存器
        reg [DATA_WIDTH-1:0] dout_pipe [READ_DELAY-1:0];

        integer i;

        always @(posedge rd_clk) begin
            if (rd_en) begin
                // 第一级：从 RAM 读出
                dout_pipe[0] <= mem[rd_addr];

                // 后续各级：流水线传递
                for (i = 1; i < READ_DELAY; i = i + 1) begin
                    dout_pipe[i] <= dout_pipe[i-1];
                end
            end
        end

        // 最终输出是最后一级寄存器
        assign dout = dout_pipe[READ_DELAY-1];
    end
endgenerate

// ============================================================
// 四、读写同一地址的行为
// ============================================================
//
// 当写端口和读端口同时访问同一个地址时，
// 读出的数据是什么？
//
// 这取决于 RAM 的"写模式"：
//
// 1. 写优先（Write First / Read After Write）
//    - 读出的是新写入的数据
//    - 也叫"透明"模式
//
// 2. 读优先（Read First）
//    - 读出的是写入之前的旧数据
//
// 3. 保持（No Change）
//    - 写操作时输出保持不变
//
// 对于简单双端口 RAM（双时钟）：
//   - 因为读写在不同的时钟域，情况更复杂
//   - 同一地址的读写可能导致亚稳态或不确定数据
//   - 一般不建议同时读写同一地址
//   - 实际应用中（如异步FIFO），通过读写指针
//     的管理来避免同时访问同一地址
//
// 本设计中，如果读写同一地址：
//   - 写操作按写时钟写入
//   - 读操作按读时钟读出
//   - 读出的数据可能是旧数据、新数据、或亚稳态
//   - 这是异步双端口 RAM 的特性，使用时需要注意
// ============================================================

// ============================================================
// 五、简单双端口 vs 真双端口
// ============================================================
//
// 5.1 简单双端口 RAM（本模块）
//     - 一个写端口 + 一个读端口
//     - 写端口只能写，读端口只能读
//     - 没有写-写冲突问题
//     - 资源占用较少
//     - 典型应用：FIFO、数据缓冲
//
// 5.2 真双端口 RAM
//     - 两个端口都可以读写
//     - 需要处理两个端口同时写同一地址的冲突
//     - 资源占用较多（通常是简单双端口的2倍）
//     - 典型应用：双 CPU 共享内存、帧缓存
//
// 真双端口 RAM 的代码结构（参考）：
//
//   // 端口A读写
//   always @(posedge clk_a) begin
//       if (en_a) begin
//           if (we_a) mem[addr_a] <= din_a;
//           dout_a <= mem[addr_a];
//       end
//   end
//
//   // 端口B读写
//   always @(posedge clk_b) begin
//       if (en_b) begin
//           if (we_b) mem[addr_b] <= din_b;
//           dout_b <= mem[addr_b];
//       end
//   end
//
//   // 注意：当两个端口同时写同一地址时会有冲突
//   // 实际 FPGA 的 BRAM 中，冲突结果取决于器件特性
// ============================================================

// ============================================================
// 六、双端口 RAM 的应用
// ============================================================
//
// 1. FIFO（先入先出队列）
//    - 写端口写入数据，读端口读出数据
//    - 同步 FIFO：读写同时钟，用单端口 RAM 也可实现
//    - 异步 FIFO：读写不同时钟，必须用双端口 RAM
//
// 2. 跨时钟域数据传输
//    - 两个时钟域之间传输大量数据
//    - 写端口在快时钟域写入，读端口在慢时钟域读出
//    - 或反之
//
// 3. 数据缓冲
//    - 输入数据流和输出数据流速率不同
//    - 用双端口 RAM 做速率匹配
//
// 4. 帧缓存
//    - 一帧数据写入的同时，另一帧数据读出
//    - 常用于视频处理、图像处理
//
// 5. 乒乓缓冲（Ping-Pong Buffer）
//    - 两个缓冲交替读写
//    - 写A的时候读B，写B的时候读A
//    - 实现无缝数据传输
// ============================================================

// ============================================================
// 七、FPGA 中 BRAM 的特性
// ============================================================
//
// 以 Xilinx FPGA 为例：
//
// 7 系列 FPGA 中的 BRAM：
//   - 每个 BRAM 容量为 36Kb
//   - 可配置为 36Kb 的简单双端口
//   - 或两个 18Kb 的简单双端口
//   - 支持真双端口模式
//   - 支持异步双时钟
//   - 内置输出寄存器（可选，延迟+1拍）
//   - 支持字节写使能
//
// 使用 BRAM 的注意事项：
//   1. 必须是同步读写（异步读只能用分布式RAM）
//   2. 读延迟至少 1 个时钟周期
//   3. 复位不能复位 RAM 内容（只能复位输出寄存器）
//   4. 可以用初始文件初始化 BRAM 内容
//   5. 同一 BRAM 可以被配置为不同的宽深比
//      例如 36Kb BRAM 可以配置为：
//      - 32K x 1
//      - 16K x 2
//      - 8K x 4
//      - 4K x 9
//      - 2K x 18
//      - 1K x 36
// ============================================================

endmodule

// ============================================================
// 模块名：single_port_ram
// 功能描述：单端口RAM设计示例
//           演示同步/异步RAM、读写时序、$readmemh初始化
//           可配置数据位宽和地址深度
// 输入端口：
//   clk      - 系统时钟
//   we       - 写使能，高有效
//   en       - 使能信号，高有效（片选）
//   addr     - 地址总线
//   din      - 写入数据
// 输出端口：
//   dout     - 读出数据
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

// ============================================================
// 【RAM 基本概念】
//
// RAM（Random Access Memory，随机存取存储器）
// 是数字系统中用于存储数据的重要组件。
//
// RAM 的分类：
//
// 1. 按端口数量分：
//    - 单端口 RAM（Single Port RAM）：一组地址线，读写分时使用
//    - 简单双端口 RAM（Simple Dual Port RAM）：读端口 + 写端口独立
//    - 真双端口 RAM（True Dual Port RAM）：两组完全独立的读写端口
//
// 2. 按时钟分：
//    - 同步 RAM（Synchronous RAM）：读写操作在时钟沿进行
//    - 异步 RAM（Asynchronous RAM）：地址变化后立即输出数据
//
// 3. 按存储类型分（FPGA中）：
//    - 分布式 RAM（Distributed RAM）：用 LUT 实现，小容量
//    - 块 RAM（Block RAM）：专用 BRAM 资源，大容量
//
// 本模块实现单端口同步 RAM
// ============================================================

module single_port_ram #(
    // ============================================================
    // 参数化设计
    // 使用 parameter 定义可配置参数，方便复用
    // ============================================================
    parameter DATA_WIDTH = 8,      // 数据位宽，默认8位
    parameter ADDR_WIDTH = 4,      // 地址位宽，默认4位
    parameter MEM_DEPTH  = 16      // 存储深度，默认16个存储单元
                                   // 2^ADDR_WIDTH = MEM_DEPTH
)(
    input                         clk,     // 时钟
    input                         we,      // 写使能，1=写，0=读
    input                         en,      // 使能/片选
    input       [ADDR_WIDTH-1:0]  addr,    // 地址
    input       [DATA_WIDTH-1:0]  din,     // 写入数据
    output reg  [DATA_WIDTH-1:0]  dout     // 读出数据
);

// ============================================================
// 一、存储器数组定义
// ============================================================
//
// Verilog 中用二维数组来描述 RAM：
//   reg [位宽-1:0] 存储器名 [深度-1:0];
//
// 例如：reg [7:0] mem [15:0];
//   表示 16 个 8 位的存储单元
//   地址范围 0 ~ 15
//   每个地址存储 8 位数据
//
// 综合工具会根据数组的大小和读写方式，
// 自动推断是用分布式 RAM 还是块 RAM 来实现。
//
// 一般来说：
//   - 小容量（< 1Kbit）：综合为分布式 RAM（用 LUT）
//   - 大容量（> 1Kbit）：综合为块 RAM（BRAM）
// ============================================================

// 存储器数组声明
// DATA_WIDTH 位宽，MEM_DEPTH 深度
reg [DATA_WIDTH-1:0] mem [MEM_DEPTH-1:0];

// ============================================================
// 二、同步读写操作
// ============================================================
//
// 同步 RAM 的特点：
//   - 所有操作在时钟上升沿触发
//   - 地址、数据、控制信号都被寄存
//   - 读延迟为 1 个时钟周期（地址输入后，下一拍出数据）
//   - FPGA 中的 BRAM 都是同步 RAM
//
// 读写时序（同步 RAM）：
//
// 时钟:   ┌──┐  ┌──┐  ┌──┐  ┌──┐  ┌──┐
//         │  │  │  │  │  │  │  │  │  │
//       ──┘  └──┘  └──┘  └──┘  └──┘  └──
//
// 地址:   A0     A1     A2     A3
//         │      │      │      │
//       --┌──────┐──────┬──────┐
//         │      │      │      │
//         └──────┴──────┴──────┴--
//
// 写使能:  低     高     低     低
//
// 读数据:         D0     D2     D3
//                       （延迟1拍）
//
// 说明：
//   第1个时钟沿：地址A0，we=0（读）
//   第2个时钟沿：读出 D0（地址A0的数据），同时地址A1，we=1（写）
//   第3个时钟沿：写入 D1 到 A1（din的值），同时地址A2，we=0（读）
//   第4个时钟沿：读出 D2（地址A2的数据）
//
// 注意：同步读的输出延迟一个时钟周期
// ============================================================

// ------------------------------------------------------------
// 同步 RAM 读写操作
// 所有操作在时钟上升沿进行
// ------------------------------------------------------------

always @(posedge clk) begin
    if (en) begin  // 使能有效时才操作
        if (we) begin
            // 写操作：将 din 写入 addr 指定的存储单元
            mem[addr] <= din;
            // 写操作时，dout 的行为取决于 RAM 类型：
            // - 写优先（Write First）：写的同时读出刚写入的数据
            // - 读优先（Read First）：写的同时读出旧数据
            // - 保持（No Change）：写操作时输出保持不变
            // 这里选择"保持"模式，写操作时输出不变
            dout <= dout;
        end
        else begin
            // 读操作：将 addr 指定的存储单元的数据读出到 dout
            dout <= mem[addr];
        end
    end
    else begin
        // 使能无效时，输出保持（可选，也可以输出高阻）
        dout <= dout;
    end
end

// ============================================================
// 三、异步 RAM 写法（参考）
// ============================================================
//
// 异步 RAM 的特点：
//   - 地址变化后，输出立即变化（不等待时钟）
//   - 读延迟为 0（组合逻辑输出）
//   - 通常用分布式 RAM 实现
//   - 速度较慢，容量较小
//
// 异步 RAM 的代码写法：
//
//   // 写操作是同步的
//   always @(posedge clk) begin
//       if (en && we) begin
//           mem[addr] <= din;
//       end
//   end
//
//   // 读操作是异步的（组合逻辑）
//   assign dout = mem[addr];
//
// 注意：
//   - 异步读虽然响应快，但容易产生毛刺
//   - FPGA 中一般推荐使用同步 RAM（BRAM 效率高）
//   - 异步 RAM 通常只用于小容量、低速场合
// ============================================================

// ============================================================
// 四、存储器初始化（$readmemh / $readmemb）
// ============================================================
//
// 在仿真中，可以用系统任务初始化 RAM 的内容：
//   $readmemh("filename", mem_name);  // 十六进制文件
//   $readmemb("filename", mem_name);  // 二进制文件
//
// 这两个系统任务在综合时也被很多工具支持，
// 可以用来给 FPGA 中的 RAM 赋初值（生成 .mif / .coe 文件）。
//
// 文件格式：
//   - 每行一个数据
//   - 支持注释（// 或 /* */）
//   - 数据可以是十六进制或二进制
//   - 数据数量可以少于存储器深度（未初始化的为 X）
//
// 示例（init_ram.mem）：
//   0A
//   1B
//   2C
//   @5  // 从地址5开始
//   FF
//   EE
//
// 注意：
//   - $readmemh / $readmemb 是仿真系统任务
//   - 大多数 FPGA 综合工具支持在 initial 块中使用
//   - 用于初始化 BRAM 的初始内容
//   - 初始数据文件路径通常是相对于仿真工程目录的
// ============================================================

// synthesis translate_off
// 综合时忽略这段代码（仅仿真用）
// 实际上很多综合工具也支持 initial 块初始化 RAM
initial begin
    // 方法1：用 $readmemh 从文件读取初始数据
    // $readmemh("init_ram.hex", mem);
    // 需要在工程目录下有 init_ram.hex 文件

    // 方法2：手动初始化（适合小容量）
    mem[0] = 8'h00;
    mem[1] = 8'h01;
    mem[2] = 8'h02;
    mem[3] = 8'h03;
    mem[4] = 8'h04;
    mem[5] = 8'h05;
    mem[6] = 8'h06;
    mem[7] = 8'h07;
    mem[8] = 8'h08;
    mem[9] = 8'h09;
    mem[10] = 8'h0A;
    mem[11] = 8'h0B;
    mem[12] = 8'h0C;
    mem[13] = 8'h0D;
    mem[14] = 8'h0E;
    mem[15] = 8'h0F;
end
// synthesis translate_on

// ============================================================
// 五、FPGA 中 RAM 的实现方式
// ============================================================
//
// 5.1 分布式 RAM（Distributed RAM）
//     - 用 FPGA 的 LUT（查找表）实现
//     - 特点：容量小、速度快、配置灵活
//     - 适用：小容量缓存、移位寄存器、FIFO
//     - 通常是异步读（组合逻辑输出）
//
// 5.2 块 RAM（Block RAM, BRAM）
//     - FPGA 中专用的 RAM 资源
//     - 特点：容量大（每个 4.5Kb/9Kb/18Kb/36Kb）、同步读写
//     - 适用：大容量数据存储、帧缓存、大FIFO
//     - 只能是同步读
//
// 5.3 综合工具如何选择？
//     - 根据容量：小容量用分布式，大容量用 BRAM
//     - 根据读写方式：异步读只能用分布式
//     - 可以用综合属性强制指定：
//       (* ram_style = "block" *)     // 强制用 BRAM
//       (* ram_style = "distributed" *) // 强制用分布式
//
// 示例（使用综合属性）：
//   (* ram_style = "block" *) reg [7:0] mem [255:0];
//   // 强制使用 BRAM 实现
//
// ============================================================

// ============================================================
// 六、单端口 RAM 的应用场景
// ============================================================
//
// 1. 寄存器堆（Register File）
//    - CPU 中的通用寄存器
//    - 单端口或双端口
//
// 2. 数据缓冲
//    - 临时存储处理过程中的数据
//    - 读写不需要同时进行
//
// 3. 查找表（LUT）
//    - 存储函数表、三角函数表
//    - 用地址作为输入，数据作为输出
//
// 4. 状态存储
//    - 存储多个通道的状态信息
//
// 当需要同时读写时，就需要双端口 RAM 或 FIFO。
// ============================================================

endmodule

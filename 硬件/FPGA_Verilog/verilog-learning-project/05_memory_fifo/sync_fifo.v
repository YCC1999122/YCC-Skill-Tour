// ============================================================
// 模块名：sync_fifo
// 功能描述：同步FIFO设计示例
//           演示空满标志判断、读写指针、深度计算、FWFT模式
//           读写共用同一时钟的先入先出队列
// 输入端口：
//   clk      - 系统时钟（读写共用）
//   rst_n    - 复位信号，低有效，异步复位
//   wr_en    - 写使能，高有效
//   rd_en    - 读使能，高有效
//   din      - 写入数据
// 输出端口：
//   dout     - 读出数据
//   full     - 满标志，高有效
//   empty    - 空标志，高有效
//   data_cnt - FIFO 中数据个数
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

// ============================================================
// 【FIFO 基本概念】
//
// FIFO（First In First Out，先入先出）
// 是一种常用的数据缓冲结构，特点是：
//   - 数据按写入顺序读出
//   - 写入端叫写端口（Write Port）
//   - 读出端叫读端口（Read Port）
//
// FIFO 的分类：
//
// 1. 同步 FIFO（Synchronous FIFO）
//    - 读写使用同一个时钟
//    - 结构简单，容易设计
//    - 用于相同时钟域内的数据缓冲
//
// 2. 异步 FIFO（Asynchronous FIFO）
//    - 读写使用不同的时钟
//    - 需要处理跨时钟域问题
//    - 结构复杂，需要格雷码指针
//    - 用于不同时钟域之间的数据传输
//
// 本模块实现同步 FIFO
//
// FIFO 的核心要素：
//   - 存储体：通常用 RAM 实现
//   - 写指针：指向下一个要写入的地址
//   - 读指针：指向下一个要读出的地址
//   - 空标志：FIFO 中没有数据时为 1
//   - 满标志：FIFO 已满时为 1
//   - 数据计数：FIFO 中当前的数据个数
// ============================================================

module sync_fifo #(
    // ============================================================
    // 参数定义
    // ============================================================
    parameter DATA_WIDTH = 8,      // 数据位宽，默认8位
    parameter ADDR_WIDTH = 4,      // 地址位宽，默认4位
                                   // 注意：实际深度是 2^ADDR_WIDTH
                                   // ADDR_WIDTH=4 对应 16 个存储单元
    parameter FWFT_MODE  = 0       // FWFT 模式使能
                                   // 0 = 标准模式（读延迟1拍）
                                   // 1 = FWFT 模式（首字直接出现在输出）
)(
    input                         clk,       // 系统时钟
    input                         rst_n,     // 复位信号，低有效
    input                         wr_en,     // 写使能
    input                         rd_en,     // 读使能
    input       [DATA_WIDTH-1:0]  din,       // 写入数据
    output      [DATA_WIDTH-1:0]  dout,      // 读出数据
    output reg                    full,      // 满标志
    output reg                    empty,     // 空标志
    output reg  [ADDR_WIDTH:0]    data_cnt   // 数据个数（ADDR_WIDTH+1位，因为要表示0~深度）
);

// ============================================================
// 一、内部信号定义
// ============================================================

localparam MEM_DEPTH = 1 << ADDR_WIDTH;  // 存储深度 = 2^ADDR_WIDTH

reg [ADDR_WIDTH-1:0] wr_ptr;  // 写指针，指向下一个要写入的地址
reg [ADDR_WIDTH-1:0] rd_ptr;  // 读指针，指向下一个要读出的地址

// 存储体：用二维数组实现
// 也可以例化前面的 simple_dual_port_ram 模块
reg [DATA_WIDTH-1:0] mem [MEM_DEPTH-1:0];

// ============================================================
// 二、写指针逻辑
// ============================================================
//
// 写指针初始值为 0
// 每写入一个数据，写指针加 1
// 写指针指向"下一个要写入的地址"
//
// 写操作条件：wr_en 有效 且 full 为 0（FIFO 未满）
// ============================================================

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        wr_ptr <= {ADDR_WIDTH{1'b0}};  // 复位时写指针归零
    end
    else if (wr_en && !full) begin
        // 写使能有效且 FIFO 未满时，写指针加 1
        wr_ptr <= wr_ptr + 1'b1;
    end
end

// ============================================================
// 三、读指针逻辑
// ============================================================
//
// 读指针初始值为 0
// 每读出一个数据，读指针加 1
// 读指针指向"下一个要读出的地址"
//
// 读操作条件：rd_en 有效 且 empty 为 0（FIFO 未空）
// ============================================================

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        rd_ptr <= {ADDR_WIDTH{1'b0}};  // 复位时读指针归零
    end
    else if (rd_en && !empty) begin
        // 读使能有效且 FIFO 未空时，读指针加 1
        rd_ptr <= rd_ptr + 1'b1;
    end
end

// ============================================================
// 四、数据计数器
// ============================================================
//
// 数据计数器记录 FIFO 中当前有多少个数据
//
// 计数器变化规则：
//   - 只写不读：data_cnt + 1
//   - 只读不写：data_cnt - 1
//   - 同时读写：data_cnt 不变
//   - 都不操作：data_cnt 不变
//
// data_cnt 的位宽是 ADDR_WIDTH + 1
// 因为需要表示 0 ~ MEM_DEPTH（共 MEM_DEPTH+1 种值）
// 例如深度为 16 时，data_cnt 需要 5 位（0~16）
// ============================================================

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        data_cnt <= {(ADDR_WIDTH+1){1'b0}};  // 复位时数据计数为0
    end
    else begin
        case ({wr_en && !full, rd_en && !empty})
            2'b10: begin  // 只写不读
                data_cnt <= data_cnt + 1'b1;
            end
            2'b01: begin  // 只读不写
                data_cnt <= data_cnt - 1'b1;
            end
            2'b11: begin  // 同时读写
                data_cnt <= data_cnt;  // 数量不变
            end
            2'b00: begin  // 都不操作
                data_cnt <= data_cnt;  // 数量不变
            end
        endcase
    end
end

// ============================================================
// 五、空满标志生成
// ============================================================
//
// 空标志 empty：
//   - 当 data_cnt == 0 时，empty = 1
//   - 表示 FIFO 中没有数据，不能读
//
// 满标志 full：
//   - 当 data_cnt == MEM_DEPTH 时，full = 1
//   - 表示 FIFO 已满，不能写
//
// 另一种判断空满的方法（不用计数器）：
//   - 空：wr_ptr == rd_ptr（且上一次操作不是写）
//   - 满：wr_ptr == rd_ptr（且上一次操作是写）
//   - 需要额外一位来区分空和满
//   （因为指针相等时可能是空也可能是满）
//
// 本设计使用计数器法，更直观易懂
// ============================================================

// 空标志：数据个数为 0 时为空
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        empty <= 1'b1;  // 复位时为空
    end
    else begin
        empty <= (data_cnt == {(ADDR_WIDTH+1){1'b0}});
    end
end

// 满标志：数据个数等于深度时为满
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        full <= 1'b0;  // 复位时未满
    end
    else begin
        full <= (data_cnt == MEM_DEPTH[ADDR_WIDTH:0]);
    end
end

// ============================================================
// 六、存储体读写操作
// ============================================================
//
// 写操作：在写使能且未满时，将数据写入 wr_ptr 指向的地址
// 读操作：在读使能且未空时，从 rd_ptr 指向的地址读出数据
//
// 这里用简单双端口的方式实现：
//   - 写端口：wr_clk=clk, wr_addr=wr_ptr
//   - 读端口：rd_clk=clk, rd_addr=rd_ptr
// ============================================================

// 写操作
always @(posedge clk) begin
    if (wr_en && !full) begin
        mem[wr_ptr] <= din;
    end
end

// ============================================================
// 七、读数据输出（标准模式 vs FWFT 模式）
// ============================================================
//
// 7.1 标准模式（Standard Mode）
//     - 读使能有效后，下一个时钟周期才输出数据
//     - 读延迟 = 1 个时钟周期
//     - 空标志拉高时，输出无效
//     - 也叫"读延迟模式"
//
// 时序图（标准模式）：
//   clk:    ┌─┐ ┌─┐ ┌─┐ ┌─┐ ┌─┐
//           │ │ │ │ │ │ │ │ │ │
//         ──┘ └─┘ └─┘ └─┘ └─┘ └─
//   rd_en:    ┌─────┐     ┌───┐
//             │     │     │   │
//         ────┘     └─────┘   └──
//   rd_ptr:   0     1     2  2  3
//   dout:         D0    D1     D2
//                 （延迟1拍）
//
// 7.2 FWFT 模式（First Word Fall Through）
//     - 首字直通模式
//     - FIFO 中有数据时，第一个数据自动出现在输出端口
//     - 读使能有效时，读取当前输出的数据，
//       同时下一个数据自动出现在输出端口
//     - 读延迟 = 0（组合逻辑输出）
//     - 也叫"预取模式"
//
// 时序图（FWFT 模式）：
//   clk:    ┌─┐ ┌─┐ ┌─┐ ┌─┐
//           │ │ │ │ │ │ │ │
//         ──┘ └─┘ └─┘ └─┘ └─
//   empty:  ──┐         ┌───
//             │         │
//             └─────────┘
//   dout:   XX D0 D1 D2 XX
//           （空时无效，有数据就输出）
//   rd_en:        ┌──┐  ┌──┐
//                 │  │  │  │
//         ────────┘  └──┘  └──
//
// FWFT 的实现原理：
//   - dout 直接等于 mem[rd_ptr]（组合逻辑）
//   - 只要 FIFO 非空，dout 就是第一个数据
//   - rd_en 有效时，rd_ptr 加 1，dout 自动更新
//
// 本设计通过参数 FWFT_MODE 选择模式
// ============================================================

generate
    if (FWFT_MODE == 1) begin : gen_fwft
        // FWFT 模式：组合逻辑输出
        // 数据直接从 mem[rd_ptr] 输出
        // 只要 FIFO 非空，dout 就是第一个数据
        assign dout = mem[rd_ptr];
    end
    else begin : gen_standard
        // 标准模式：寄存器输出
        // 读使能后，下一拍才输出数据
        reg [DATA_WIDTH-1:0] dout_reg;

        always @(posedge clk or negedge rst_n) begin
            if (!rst_n) begin
                dout_reg <= {DATA_WIDTH{1'b0}};
            end
            else if (rd_en && !empty) begin
                dout_reg <= mem[rd_ptr];
            end
            // 其他情况保持
        end

        assign dout = dout_reg;
    end
endgenerate

// ============================================================
// 八、FIFO 深度计算
// ============================================================
//
// FIFO 深度（Depth）是指 FIFO 能存储多少个数据。
// 深度需要根据应用场景合理选择：
//
// 影响深度的因素：
// 1. 读写速率差
//    - 写速率 > 读速率：FIFO 会被写满
//    - 写速率 = 读速率：理论上深度为1即可
//    - 突发写入：需要缓冲突发数据
//
// 2. 数据突发长度
//    - 如果有连续 N 个数据的突发写入，
//      而读端来不及读出，深度至少为 N
//
// 3. 系统延迟
//    - 读端响应延迟越大，需要的深度越大
//
// 深度计算公式（同步FIFO，突发模式）：
//   深度 = 突发长度 - (突发长度 / 读写速率比)
//
// 示例：
//   写速率 100MHz，读速率 50MHz
//   突发长度 100 个数据
//   突发期间写入 100 个，读出 50 个
//   所以深度至少需要 100 - 50 = 50
//   实际使用时建议留 10%~20% 的余量
//
// 注意：
//   - 本设计的实际深度是 2^ADDR_WIDTH
//   - 如果需要非2的幂次深度，需要额外的地址判断
//   - FPGA 中 BRAM 的深度通常是 2 的幂次
// ============================================================

// ============================================================
// 九、FIFO 设计注意事项
// ============================================================
//
// 9.1 避免非法操作
//     - 满时继续写：会导致数据丢失（或覆盖）
//     - 空时继续读：会读出无效数据
//     - 实际工程中必须检查空满标志
//
// 9.2 亚稳态问题
//     - 同步 FIFO 没有亚稳态问题
//     - 异步 FIFO 需要特殊处理（格雷码指针）
//
// 9.3 几乎空/几乎满（Almost Empty / Almost Full）
//     - 实际工程中常用 prog_empty / prog_full
//     - 提前通知系统 FIFO 快空/快满了
//     - 给系统留出反应时间
//     - 可以在本设计基础上添加：
//       assign almost_empty = (data_cnt <= THRESHOLD);
//       assign almost_full  = (data_cnt >= MEM_DEPTH - THRESHOLD);
//
// 9.4 复位策略
//     - 异步复位：简单，但释放时可能有亚稳态
//     - 同步复位：安全，但需要时钟
//     - FIFO 复位时所有指针和计数器都清零
//
// 9.5 综合实现
//     - 小容量 FIFO：用分布式 RAM + 寄存器
//     - 大容量 FIFO：用 BRAM
//     - FPGA 厂商通常提供现成的 FIFO IP 核
//       （如 Xilinx 的 FIFO Generator）
//     - 自己写 FIFO 主要用于学习或特殊需求
// ============================================================

// ============================================================
// 十、同步 FIFO vs 异步 FIFO
// ============================================================
//
// 同步 FIFO（本模块）：
//   - 读写同一个时钟
//   - 空满标志用计数器或指针比较
//   - 设计简单
//   - 用于相同时钟域内的数据缓冲
//
// 异步 FIFO：
//   - 读写不同时钟
//   - 空满标志需要跨时钟域判断
//   - 读写指针用格雷码编码（减少亚稳态）
//   - 需要两级同步器
//   - 设计复杂，容易出错
//   - 用于跨时钟域的数据传输
//
// 异步 FIFO 的关键技术：
//   1. 格雷码指针：相邻状态只有一位变化
//      跨时钟域采样时最多一位出错，
//      不会出现多位同时翻转的亚稳态扩散
//   2. 两级同步器：将指针同步到对方时钟域
//   3. 空满判断：
//      - 写满：写指针追上读指针
//      - 读空：读指针追上写指针
// ============================================================

endmodule

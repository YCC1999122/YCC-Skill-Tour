// ============================================================
// 模块名：data_types
// 功能描述：Verilog数据类型详解
//           演示 wire/reg/integer/real/parameter/localparam
// 输入端口：
//   clk      - 系统时钟
//   rst_n    - 复位信号，低有效
//   data_in  - 输入数据，8位
// 输出端口：
//   data_out - 输出数据，8位
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

module data_types (
    input             clk,
    input             rst_n,
    input       [7:0] data_in,
    output reg  [7:0] data_out
);

// ============================================================
// parameter 类型：参数
// 可以在模块实例化时被修改（通过 defparam 或 #() 传递）
// 常用于定义位宽、深度、延时等可配置参数
// 参数是常量，不能在程序运行时修改
// ============================================================

// parameter 定义的是模块级参数
parameter DATA_WIDTH = 8;              // 数据位宽，默认8位
parameter ADDR_WIDTH = 4;              // 地址位宽，默认4位
parameter DATA_DEPTH = 1 << ADDR_WIDTH; // 数据深度，2的ADDR_WIDTH次方 = 16
                                    // << 是左移运算符，1<<4 = 16

parameter DELAY_TIME = 5;              // 延时时间，单位ns（仅仿真用）
parameter IDLE_STATE = 2'b00;          // 空闲状态编码

// ============================================================
// localparam 类型：局部参数
// 不能在模块实例化时被修改，作用域仅限于本模块
// 常用于定义状态机编码、内部常量等
// ============================================================

localparam S_IDLE  = 2'b00;            // 空闲状态
localparam S_START = 2'b01;            // 开始状态
localparam S_RUN   = 2'b10;            // 运行状态
localparam S_DONE  = 2'b11;            // 完成状态

localparam MAX_VALUE = 8'hFF;          // 8位最大值，十六进制FF = 255
localparam MIN_VALUE = 8'd0;           // 8位最小值，十进制0

// ============================================================
// wire 类型：网线型变量
// 1. 表示物理导线，不存储值，只起连接作用
// 2. 值由驱动它的源（如assign语句、模块输出）决定
// 3. 如果没有驱动源，值为高阻态 Z
// 4. 不能在 always 块中被赋值
// 5. input/output 端口默认是 wire 类型
// ============================================================

// 普通1位 wire 信号
wire enable;                           // 使能信号
wire valid;                            // 有效信号

// 多位 wire 信号
wire [7:0] sum;                        // 8位加法结果
wire [15:0] product;                   // 16位乘法结果

// 向量型 wire：[高位:低位] 或 [低位:高位]，推荐 [高位:低位]
wire [DATA_WIDTH-1:0] data_wire;       // 参数化位宽的wire

// ============================================================
// reg 类型：寄存器型变量
// 1. 在 always 块或 initial 块中被赋值的变量必须声明为 reg
// 2. reg 在仿真中可以存储值
// 3. 注意：reg 不一定对应物理寄存器！
//    - 在时序逻辑（@posedge clk）中赋值 → 综合为触发器
//    - 在组合逻辑（@(*)）中赋值 → 综合为组合逻辑（线网）
// 4. 不能用 assign 语句给 reg 赋值
// ============================================================

// 普通1位 reg 信号
reg flag;                              // 标志位
reg start;                             // 启动信号

// 多位 reg 信号
reg [7:0] counter;                     // 8位计数器
reg [3:0] state;                       // 4位状态寄存器
reg [DATA_WIDTH-1:0] data_reg;         // 参数化位宽的reg

// ============================================================
// integer 类型：整数类型
// 1. 32位有符号整数
// 2. 主要用于仿真中的循环变量、文件操作等
// 3. 可综合，但通常不建议用于实际硬件描述
// 4. 数学运算时会自动进行有符号数处理
// ============================================================

integer i;                              // 循环变量
integer j;                              // 循环变量
integer result;                         // 整数结果

// ============================================================
// real 类型：实数类型
// 1. 双精度浮点数
// 2. 仅用于仿真，不可综合
// 3. 用于计算延迟、功耗等实数运算
// ============================================================

real pi = 3.1415926;                   // 圆周率
real period = 10.5;                    // 时钟周期，单位ns
real duty_cycle = 0.5;                 // 占空比

// ============================================================
// 其他数据类型简介（了解即可）
// ============================================================

// time 类型：64位无符号整数，存储仿真时间
// time current_time;

// realtime 类型：实数时间
// realtime sim_time;

// genvar 类型：生成块循环变量
// genvar g;

// ============================================================
// 常量表示方法：<位宽>'<进制><数字>
// 进制：b(二进制)、o(八进制)、d(十进制)、h(十六进制)
// ============================================================

// 位宽可以省略，省略时默认32位
// 8位二进制表示
wire [7:0] bin_val = 8'b1010_1100;    // 8位二进制，下划线仅用于阅读分隔
// 8位十进制表示
wire [7:0] dec_val = 8'd172;           // 8位十进制 172
// 8位十六进制表示
wire [7:0] hex_val = 8'hAC;            // 8位十六进制 AC
// 8位八进制表示
wire [7:0] oct_val = 8'o254;           // 8位八进制 254

// 特殊值
// 0/1：逻辑0/1
// x/X：未知值（仿真中使用，可能是0也可能是1）
// z/Z：高阻态（三态门断开）

wire [7:0] unknown = 8'hxx;            // 8位未知值
wire [7:0] highz = 8'hzz;              // 8位高阻态

// ============================================================
// 连续赋值示例
// ============================================================

// wire 类型信号必须用 assign 赋值
assign enable = rst_n;                 // 复位释放后使能有效
assign sum = data_in + data_out;       // 加法结果
assign data_wire = data_in;            // 输入连接到内部wire

// ============================================================
// 时序逻辑示例
// 在 always 块中赋值的信号必须是 reg 类型
// ============================================================

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // 复位时初始化所有寄存器
        data_out <= 8'd0;
        counter <= 8'd0;
        flag <= 1'b0;
        state <= S_IDLE;              // 使用localparam定义的状态
        data_reg <= 8'd0;
    end
    else begin
        // 计数器累加
        counter <= counter + 1'b1;
        
        // 数据寄存
        data_reg <= data_in;
        data_out <= data_reg;
        
        // 标志位：当计数器达到最大值时置1
        if (counter == MAX_VALUE - 1) begin
            flag <= 1'b1;
            state <= S_DONE;
        end
        else begin
            flag <= 1'b0;
            state <= S_RUN;
        end
    end
end

// ============================================================
// generate 块示例
// genvar 用于 generate 块中的循环变量
// 可以生成多个相同的硬件模块
// ============================================================

genvar g;
generate
    // 生成4个相同的逻辑单元
    for (g = 0; g < 4; g = g + 1) begin : gen_loop
        // 每个循环生成一个assign语句
        // gen_loop[g].xxx 可以访问每个生成块中的信号
    end
endgenerate

endmodule

// ============================================================
// 模块名：module_example
// 功能描述：Verilog模块结构示例
//           演示 module/endmodule、端口声明、input/output/inout
// 输入端口：
//   clk      - 系统时钟，上升沿触发
//   rst_n    - 复位信号，低有效
//   a        - 输入数据a，4位位宽
//   b        - 输入数据b，4位位宽
//   sel      - 选择信号，1位
// 输出端口：
//   c        - 输出数据c，4位位宽
//   d        - 输出数据d，寄存器类型，4位位宽
// 双向端口：
//   io_data  - 双向数据端口，8位位宽
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

// module 关键字：定义一个模块的开始
// module_example 是模块名，模块名必须与文件名一致（推荐）
// 端口列表在括号内声明，端口之间用逗号分隔
module module_example (
    // input 关键字：声明输入端口
    // 信号从模块外部流入模块内部
    input         clk,      // 时钟信号，1位宽（默认位宽为1位）
    input         rst_n,    // 复位信号，低有效，1位宽
    input  [3:0]  a,        // 输入数据a，4位位宽
                          // [3:0] 表示位宽，最高位是第3位，最低位是第0位
                          // 共有 3-0+1 = 4 位
    input  [3:0]  b,        // 输入数据b，4位位宽
    input         sel,      // 选择信号，1位宽
    
    // output 关键字：声明输出端口
    // 信号从模块内部流出到模块外部
    output [3:0]  c,        // 输出数据c，4位位宽，wire类型（默认）
    output reg [3:0]  d,    // 输出数据d，4位位宽，reg类型
                          // reg 表示该信号在always块中被赋值
                          // 注意：output 默认是 wire 类型，要在always中赋值必须加 reg
    
    // inout 关键字：声明双向端口
    // 信号既可以输入也可以输出，常用于总线接口
    inout  [7:0]  io_data   // 双向数据端口，8位位宽
);

// ============================================================
// 内部信号声明区域
// 在模块内部定义的信号，不能被外部模块直接访问
// ============================================================

// wire 类型：网线型变量，用于连接各个模块或逻辑单元
// wire 就像真实的导线，本身不存储值，值由驱动它的源决定
wire [3:0] sum;           // 加法结果，4位wire型
wire [3:0] mux_out;       // 多路选择器输出，4位wire型

// reg 类型：寄存器型变量，在always块中被赋值
// reg 在仿真中可以存储值，但综合后不一定是物理寄存器
// 只有在时序逻辑（posedge clk）中赋值的reg才会被综合为触发器
reg  [7:0] io_out_reg;    // 双向端口输出寄存器
reg        io_dir;        // 双向端口方向控制，1为输出，0为输入

// ============================================================
// 连续赋值语句（assign）
// 用于组合逻辑，只要右侧表达式变化，左侧就会立即更新
// 类似于电路中导线的连接关系
// ============================================================

// assign 关键字：连续赋值语句
// 右侧的 a + b 是加法运算，结果赋值给左侧的 sum
// 只要 a 或 b 的值发生变化，sum 就会立即更新
assign sum = a + b;       // 加法运算，结果连接到sum

// 条件运算符（三元运算符）： condition ? true_value : false_value
// 如果 sel 为1，则选择 a；否则选择 b
// 这是一个2选1多路选择器的数据流描述方式
assign mux_out = sel ? a : b;

// 将 mux_out 连接到输出端口 c
// 因为 c 默认是 wire 类型，所以必须用 assign 赋值
assign c = mux_out;

// 双向端口的描述方式
// 当 io_dir 为1时，io_data 作为输出，输出 io_out_reg 的值
// 当 io_dir 为0时，io_data 作为输入，呈高阻态（Z）
// 高阻态 Z 表示该引脚不驱动总线，外部信号可以输入
assign io_data = io_dir ? io_out_reg : 8'hzz;  // hh表示十六进制，zz表示高阻

// ============================================================
// 时序逻辑 always 块
// 敏感列表：@(posedge clk or negedge rst_n)
//   posedge clk：时钟上升沿触发（0→1跳变时执行）
//   negedge rst_n：复位下降沿触发（1→0跳变时执行，即复位有效时）
//   or：两个条件满足任一就执行
// ============================================================

// always 关键字：过程块，只要敏感列表中的条件满足就执行
// 这是一个时序逻辑块，所有在其中赋值的reg信号会被综合为触发器
always @(posedge clk or negedge rst_n) begin
    // if-else 分支语句
    // 如果复位信号无效（低有效，rst_n == 0 表示复位有效）
    if (!rst_n) begin
        // 复位时给 d 赋初值
        // ! 是逻辑非运算符
        d <= 4'd0;         // 4位十进制的0
        io_out_reg <= 8'd0;
        io_dir <= 1'b0;    // 复位时设为输入方向
    end
    else begin
        // 时钟上升沿时执行
        // 将加法结果延迟一个时钟周期后输出到 d
        // <= 是非阻塞赋值，用于时序逻辑
        // 非阻塞赋值：所有赋值在块结束时同时更新
        d <= sum;
        
        // 当 sel 为1时，双向端口设为输出模式
        if (sel) begin
            io_dir <= 1'b1;
            io_out_reg <= {4'd0, a};  // { } 是拼接运算符
        end
        else begin
            io_dir <= 1'b0;           // 输入模式
        end
    end
end

// ============================================================
// endmodule 关键字：模块定义结束
// 每个 module 必须对应一个 endmodule
// ============================================================

endmodule

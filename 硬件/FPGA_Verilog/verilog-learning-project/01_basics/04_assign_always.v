// ============================================================
// 模块名：assign_always
// 功能描述：连续赋值与过程块详解
//           演示 assign / always / initial 的用法和区别
// 输入端口：
//   clk      - 系统时钟，50MHz
//   rst_n    - 复位信号，低有效
//   a        - 输入数据a，4位
//   b        - 输入数据b，4位
//   c        - 输入数据c，4位
// 输出端口：
//   sum_assign   - assign 赋值的加法结果
//   sum_comb     - 组合always块的加法结果
//   sum_seq      - 时序always块的加法结果（延迟1拍）
//   d_ff         - D触发器输出
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

module assign_always (
    input             clk,         // 系统时钟
    input             rst_n,       // 复位信号，低有效
    input       [3:0] a,           // 输入数据a
    input       [3:0] b,           // 输入数据b
    input       [3:0] c,           // 输入数据c
    output      [3:0] sum_assign,  // assign赋值结果
    output reg  [3:0] sum_comb,    // 组合逻辑always结果
    output reg  [3:0] sum_seq,     // 时序逻辑always结果
    output reg  [3:0] d_ff         // D触发器输出
);

// ============================================================
// 一、连续赋值语句 assign
// 特点：
// 1. 并行执行：所有assign语句同时执行，不分先后
// 2. 实时更新：右侧表达式变化时，左侧立即更新
// 3. 只能给 wire 类型赋值（output默认是wire）
// 4. 用于描述组合逻辑电路
// 5. 不能在 always/initial 块内部使用
// ============================================================

// assign 语句 1：a + b 的结果直接输出
// 只要 a 或 b 变化，sum_assign 立刻变化（延迟为0）
assign sum_assign = a + b;

// assign 语句 2：可以使用条件运算符
// 这是一个带使能的缓冲器描述
wire enable;
assign enable = rst_n;  // 复位释放后使能

// 多个 assign 语句并行执行，顺序不影响结果
wire [3:0] temp;
assign temp = a + b + c;

// ============================================================
// 二、过程块 always
// 特点：
// 1. 只有敏感列表中的事件发生时才执行
// 2. 内部语句顺序执行（仿真视角）
// 3. 只能给 reg 类型赋值
// 4. 可以描述组合逻辑或时序逻辑，取决于敏感列表
// ============================================================

// ------------------------------------------------------------
// 2.1 组合逻辑 always 块
// 敏感列表：@(*) 或 @(a or b or c)
// 特点：
//   - 只要敏感列表中的信号变化，就执行一次
//   - 综合后是组合逻辑（没有触发器）
//   - 所有分支都必须给输出赋值，否则会生成锁存器（Latch）
//   - 使用阻塞赋值 =
// ------------------------------------------------------------

// @(*) 是 Verilog-2001 新增的语法
// 自动将所有右侧表达式中的信号加入敏感列表
// 避免手动列出敏感信号导致的遗漏（仿真与综合不一致）
always @(*) begin
    // 组合逻辑内部的赋值是"顺序执行"的
    // 但综合后仍然是组合电路，只是行为描述上顺序
    // 使用阻塞赋值 = 
    sum_comb = a + b;         // 第一步：a+b
    sum_comb = sum_comb + c;  // 第二步：再加c
                           // 最终结果等于 a+b+c
end

// 上面的代码等价于：assign sum_comb = a + b + c;
// 只是写法不同，综合结果完全一样

// ------------------------------------------------------------
// 2.2 时序逻辑 always 块
// 敏感列表：@(posedge clk) 或 @(negedge clk)
// 特点：
//   - 只在时钟边沿（上升沿/下降沿）触发
//   - 综合后会生成触发器（Flip-Flop）
//   - 有记忆功能，输出保持到下一个时钟沿
//   - 使用非阻塞赋值 <=
// ------------------------------------------------------------

// posedge clk：时钟上升沿触发（0→1跳变）
// negedge rst_n：复位下降沿触发（1→0跳变，异步复位）
// 这是最常用的写法：异步复位的D触发器
always @(posedge clk or negedge rst_n) begin
    // 复位判断放在最前面
    // !rst_n 等价于 rst_n == 1'b0，表示复位有效
    if (!rst_n) begin
        // 复位状态：给寄存器赋初值
        sum_seq <= 4'd0;      // 非阻塞赋值 <=
        d_ff <= 4'd0;
    end
    else begin
        // 时钟上升沿执行
        // sum_seq 是 a+b+c 打了一拍的结果
        // 也就是时钟上升沿把 a+b+c 的值存入触发器
        sum_seq <= a + b + c;
        
        // D触发器：把输入a存入寄存器
        // 每来一个时钟上升沿，d_ff就更新为a的当前值
        d_ff <= a;
    end
end

// ============================================================
// 三、阻塞赋值 vs 非阻塞赋值
// ============================================================
//
// 阻塞赋值（Blocking Assignment）：=
//   - 执行完当前语句后，才执行下一条语句
//   - 就像软件代码一样，顺序执行
//   - 用于组合逻辑 always 块
//   - 用于 initial 块（仿真）
//
// 非阻塞赋值（Non-Blocking Assignment）：<=
//   - 所有赋值语句同时计算，在块结束时同时更新
//   - 每条语句的右侧值是块开始时的值
//   - 用于时序逻辑 always 块
//   - 避免了仿真中的竞争冒险
//
// 举例说明区别：
//
// 阻塞赋值（顺序执行）：       非阻塞赋值（并行执行）：
// always @(posedge clk)       always @(posedge clk)
// begin                       begin
//     a = b;                      a <= b;  // 用旧值b计算
//     b = c;                      b <= c;  // 用旧值c计算
//     c = d;                      c <= d;  // 用旧值d计算
// end                         end
// 结果：a=b, b=c, c=d         结果：a=b_old, b=c_old, c=d_old
// （相当于连续赋值）          （相当于移位寄存器）
//
// 【重要规则】
// 1. 时序逻辑 always 块：用非阻塞赋值 <=
// 2. 组合逻辑 always 块：用阻塞赋值 =
// 3. 不要在同一个 always 块中混用两种赋值
// 4. assign 语句只能用 =
// ============================================================

// ============================================================
// 四、initial 过程块
// 特点：
// 1. 仿真开始时执行一次，之后不再执行
// 2. 主要用于仿真测试（Testbench）
// 3. 不可综合（不能变成实际电路）
// 4. 常用于初始化信号、产生激励、显示信息等
// ============================================================

// initial 块仅在仿真中使用，综合时会被忽略
// synthesis translate_off 是综合编译指令，指示综合工具忽略这段代码
// synthesis translate_on 表示恢复综合
// synthesis translate_off
initial begin
    // $display 是系统任务，用于在仿真控制台打印信息
    $display("Time = %0t, initial block starts", $time);
    
    // 初始值设置（仅仿真用，实际电路中寄存器初值由复位决定）
    // sum_seq = 0;  // 不推荐，实际电路中无效
    
    // #10 表示延时10个时间单位
    // 只能在仿真中使用，不可综合
    #10;
    $display("Time = %0t, 10 time units passed", $time);
end
// synthesis translate_on

// ============================================================
// 五、always 块的其他用法
// ============================================================

// 5.1 带使能的D触发器
// 使能有效时，时钟上升沿更新数据
// 使能无效时，保持原值
reg [3:0] en_ff;       // 带使能的触发器输出
reg enable_reg;        // 使能信号寄存器

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        en_ff <= 4'd0;
        enable_reg <= 1'b0;
    end
    else begin
        enable_reg <= enable;
        if (enable_reg) begin  // 使能有效时才更新
            en_ff <= a;
        end
        // 使能无效时，en_ff 保持原值（因为没有赋值，所以保持）
    end
end

// 5.2 同步复位 vs 异步复位
//
// 异步复位（前面已演示）：
//   always @(posedge clk or negedge rst_n)
//   复位信号一有效，立即复位，不等待时钟
//   优点：复位响应快，不依赖时钟
//   缺点：复位释放时可能有亚稳态问题
//
// 同步复位（如下）：
//   always @(posedge clk)
//   复位信号只在时钟上升沿被采样
//   优点：复位同步于时钟，亚稳态风险低
//   缺点：复位必须持续到下一个时钟沿
//

// 同步复位示例
reg [3:0] sync_rst_ff;
wire sync_rst_n;
assign sync_rst_n = rst_n;

always @(posedge clk) begin  // 敏感列表中没有 rst_n
    if (!sync_rst_n) begin   // 只在时钟上升沿判断复位
        sync_rst_ff <= 4'd0;
    end
    else begin
        sync_rst_ff <= a;
    end
end

endmodule

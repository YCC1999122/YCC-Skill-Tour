// ============================================================
// 模块名：operators
// 功能描述：Verilog运算符详解
//           演示算术/逻辑/位运算/关系/拼接/移位/条件运算符
// 输入端口：
//   a        - 操作数a，8位
//   b        - 操作数b，8位
//   sel      - 选择信号，3位
// 输出端口：
//   result   - 运算结果，8位
//   carry    - 进位/标志位
// 作者：Verilog学习项目
// 日期：2024-01-01
// ============================================================

module operators (
    input       [7:0] a,        // 操作数a
    input       [7:0] b,        // 操作数b
    input       [2:0] sel,      // 运算选择
    output reg  [7:0] result,   // 运算结果
    output        carry         // 进位标志
);

// ============================================================
// 一、算术运算符 Arithmetic Operators
// +  加法
// -  减法
// *  乘法
// /  除法（整数除法，截断小数）
// %  取模（求余数）
// ** 幂运算（可综合支持有限）
// ============================================================

// 加法：a + b，结果位宽需要考虑进位
// 两个8位数相加，最大结果是9位（255+255=510=9位）
wire [8:0] add_result;               // 9位，包含进位
assign add_result = a + b;           // 加法运算
assign carry = add_result[8];        // 第8位是进位位

// 减法：a - b
// 结果如果是负数，用补码表示
wire [7:0] sub_result;
assign sub_result = a - b;

// 乘法：a * b
// 两个8位数相乘，结果是16位
wire [15:0] mul_result;
assign mul_result = a * b;

// 除法：a / b（整数除法）
// 注意：除数不能为0，否则结果为x（未知）
wire [7:0] div_result;
assign div_result = a / b;

// 取模：a % b（求余数）
wire [7:0] mod_result;
assign mod_result = a % b;

// ============================================================
// 二、逻辑运算符 Logical Operators
// && 逻辑与（两边都为真，结果为真）
// || 逻辑或（有一边为真，结果为真）
// !  逻辑非（取反）
// 结果为1位：1（真）或 0（假）
// 只要操作数有任何一位为1，就被视为"真"
// ============================================================

wire a_nonzero;                      // a是否非零
assign a_nonzero = (a != 8'd0);      // 比较运算，结果为1位

wire logic_and;                      // 逻辑与
assign logic_and = (a > 0) && (b > 0);  // a和b都大于0时为1

wire logic_or;                       // 逻辑或
assign logic_or = (a > 0) || (b > 0);   // a或b大于0时为1

wire logic_not;                      // 逻辑非
assign logic_not = !(a > 0);            // a不大于0时为1

// ============================================================
// 三、位运算符 Bitwise Operators
// ~  按位非（每一位取反）
// &  按位与（对应位都为1，结果位才为1）
// |  按位或（对应位有一个为1，结果位就为1）
// ^  按位异或（对应位不同，结果位为1）
// ~^ 按位同或（对应位相同，结果位为1），也可写作 ^~
// 按位运算逐位进行，结果位宽与操作数相同
// ============================================================

wire [7:0] bit_not;                  // 按位非
assign bit_not = ~a;                 // a的每一位取反

wire [7:0] bit_and;                  // 按位与
assign bit_and = a & b;              // a和b对应位相与

wire [7:0] bit_or;                   // 按位或
assign bit_or = a | b;               // a和b对应位相或

wire [7:0] bit_xor;                  // 按位异或
assign bit_xor = a ^ b;              // a和b对应位异或

wire [7:0] bit_xnor;                 // 按位同或
assign bit_xnor = a ~^ b;            // a和b对应位同或

// ============================================================
// 四、归约运算符 Reduction Operators
// 对单个操作数的所有位进行运算，结果为1位
// &  归约与（所有位相与）
// ~& 归约与非
// |  归约或（所有位相或）
// ~| 归约或非
// ^  归约异或（所有位异或，即奇偶校验）
// ~^ 归约同或
// ============================================================

wire and_reduction;                  // 归约与
assign and_reduction = &a;           // a[7]&a[6]&...&a[0]，全1则为1

wire or_reduction;                   // 归约或
assign or_reduction = |a;            // a[7]|a[6]|...|a[0]，有1则为1

wire xor_reduction;                  // 归约异或（奇偶校验）
assign xor_reduction = ^a;           // 1的个数为奇数时为1

// ============================================================
// 五、关系运算符 Relational Operators
// >  大于
// <  小于
// >= 大于等于
// <= 小于等于
// == 等于（逻辑相等，x和z参与比较结果为x）
// != 不等于
// === case相等（x和z也参与精确比较，仅仿真用）
// !== case不等
// 结果为1位：1（真）或 0（假）
// ============================================================

wire greater;                        // 大于
assign greater = (a > b);            // a大于b时为1

wire less;                           // 小于
assign less = (a < b);               // a小于b时为1

wire equal;                          // 等于
assign equal = (a == b);             // a等于b时为1

wire not_equal;                      // 不等于
assign not_equal = (a != b);         // a不等于b时为1

wire greater_eq;                     // 大于等于
assign greater_eq = (a >= b);

// ============================================================
// 六、移位运算符 Shift Operators
// <<  逻辑左移（低位补0）
// >>  逻辑右移（高位补0）
// <<< 算术左移（同逻辑左移）
// >>> 算术右移（高位补符号位）
// 移位次数为右侧操作数
// ============================================================

wire [7:0] shift_left;               // 左移1位
assign shift_left = a << 1;          // 相当于乘以2

wire [7:0] shift_right;              // 右移1位
assign shift_right = a >> 1;         // 相当于除以2（无符号）

wire [7:0] shift_left_n;             // 左移b位
assign shift_left_n = a << b[2:0];   // 按b的低3位移位

// 算术右移（需要有符号数）
// $signed() 系统函数将无符号数转为有符号数
wire signed [7:0] signed_a;
assign signed_a = $signed(a);
wire signed [7:0] arith_shift_right;
assign arith_shift_right = signed_a >>> 1;  // 高位补符号位

// ============================================================
// 七、拼接运算符 Concatenation Operator
// {信号1, 信号2, ...}
// 将多个信号按位拼接成一个宽信号
// 可以使用重复法：{次数{信号}}
// ============================================================

wire [15:0] concat_ab;               // 拼接a和b
assign concat_ab = {a, b};           // {高8位a, 低8位b} = 16位

wire [9:0] concat_3;                 // 拼接3个信号
assign concat_3 = {1'b1, a, 1'b0};   // 共1+8+1=10位

wire [7:0] replicate;                // 重复拼接
assign replicate = {4{2'b10}};       // 重复4次"10" = "10101010"

wire [7:0] sign_extend;              // 符号扩展
assign sign_extend = {{4{a[7]}}, a[3:0]};  // 将4位有符号数扩展为8位

// ============================================================
// 八、条件运算符 Conditional Operator
// condition ? true_expr : false_expr
// 也叫三元运算符
// 如果条件为真，取冒号前的值；否则取冒号后的值
// 可用于描述多路选择器
// ============================================================

wire [7:0] mux_2to1;                 // 2选1多路选择器
assign mux_2to1 = sel[0] ? a : b;    // sel[0]=1选a，sel[0]=0选b

// 嵌套条件运算符实现4选1
wire [7:0] mux_4to1;
assign mux_4to1 = (sel[1:0] == 2'b00) ? 8'd0 :
                  (sel[1:0] == 2'b01) ? a    :
                  (sel[1:0] == 2'b10) ? b    :
                  (a + b);

// ============================================================
// 九、运算符优先级（从高到低）
// 1. 一元运算符：+  -  !  ~
// 2. 乘除模：*  /  %
// 3. 加减：+  -
// 4. 移位：<<  >>  <<<  >>>
// 5. 关系：<  <=  >  >=
// 6. 相等：==  !=  ===  !==
// 7. 归约与：&  ~&
// 8. 归约异或：^  ~^  ^~
// 9. 归约或：|  ~|
// 10. 逻辑与：&&
// 11. 逻辑或：||
// 12. 条件：?:
//
// 建议：使用括号明确优先级，提高代码可读性
// ============================================================

// ============================================================
// 组合逻辑 always 块
// 使用 case 语句根据 sel 选择运算结果
// ============================================================

always @(*) begin
    case (sel)
        3'd0: result = add_result[7:0];   // 加法
        3'd1: result = sub_result;        // 减法
        3'd2: result = mul_result[7:0];   // 乘法（取低8位）
        3'd3: result = div_result;        // 除法
        3'd4: result = bit_and;           // 按位与
        3'd5: result = bit_or;            // 按位或
        3'd6: result = bit_xor;           // 按位异或
        3'd7: result = shift_left;        // 左移
        default: result = 8'd0;
    endcase
end

endmodule

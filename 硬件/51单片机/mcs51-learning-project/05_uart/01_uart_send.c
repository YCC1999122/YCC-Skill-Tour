/*****************************************************************************
 * 文件名：01_uart_send.c
 * 描述：串口发送实验 - 串口初始化与数据发送
 * 芯片：STC89C52RC
 * 晶振：11.0592MHz
 * 编译环境：Keil uVision5 / C51
 *
 * 功能说明：
 *   1. 配置串口工作在模式1（8位UART，波特率可变）
 *   2. 使用定时器2作为波特率发生器，波特率9600
 *   3. 实现单字节发送函数和字符串发送函数
 *   4. 上电后循环发送"Hello, STC89C52!\r\n"字符串
 *
 * 硬件连接：
 *   P3.0 (RXD) → USB转TTL模块的 TXD
 *   P3.1 (TXD) → USB转TTL模块的 RXD
 *   GND       → USB转TTL模块的 GND
 *   （共地非常重要，否则通信会出错）
 *
 * 学习要点：
 *   1. 串口通信基本概念（波特率、数据位、停止位、校验位）
 *   2. SCON串口控制寄存器的配置
 *   3. 定时器2作为波特率发生器的原理与配置
 *   4. SBUF发送缓冲器的使用
 *   5. TI发送中断标志的作用
 *****************************************************************************/

#include <reg52.h>          // 51单片机寄存器定义

/*************************** 宏定义区 ***************************/
// 晶振频率定义，用于波特率计算
#define FOSC        11059200L    // 晶振频率：11.0592MHz
#define BAUDRATE    9600         // 波特率：9600bps

/*************************** 函数声明区 ***************************/
void UART_Init(void);          // 串口初始化函数声明
void UART_SendByte(unsigned char dat);  // 发送单字节函数声明
void UART_SendString(unsigned char *str); // 发送字符串函数声明
void Delay_ms(unsigned int ms);         // 毫秒级延时函数声明

/*************************** 主函数 ***************************/
/************************************************************
 * 函数名：main
 * 功能：主函数，程序入口
 * 参数：无
 * 返回值：无
 * 说明：
 *   初始化串口后，循环发送测试字符串
 *   打开串口助手，设置波特率9600、8位数据、1位停止位、无校验
 *   即可看到单片机发送的数据
 ************************************************************/
void main(void)
{
    UART_Init();   // 初始化串口

    while(1)
    {
        // 发送字符串
        // 字符串末尾的 \r\n 是回车换行符
        // \r (0x0D) - 回车，光标回到行首
        // \n (0x0A) - 换行，光标移到下一行
        UART_SendString("Hello, STC89C52!\r\n");

        Delay_ms(1000);  // 每隔1秒发送一次
    }
}

/*************************** 串口初始化函数 ***************************/
/************************************************************
 * 函数名：UART_Init
 * 功能：初始化串口，配置波特率为9600
 * 参数：无
 * 返回值：无
 *
 * 配置说明：
 *   1. 串口工作模式：模式1（8位UART，波特率可变）
 *   2. 波特率发生器：定时器2（16位自动重装）
 *   3. 波特率：9600bps
 *   4. 允许接收（REN=1），本实验只用发送也可以关闭
 *
 * 定时器2波特率计算公式：
 *   波特率 = 晶振频率 / (32 * (65536 - RCAP2))
 *   推导得：RCAP2 = 65536 - 晶振频率 / (32 * 波特率)
 *
 *   代入数值（11.0592MHz，9600波特率）：
 *   RCAP2 = 65536 - 11059200 / (32 * 9600)
 *         = 65536 - 11059200 / 307200
 *         = 65536 - 36
 *         = 65500
 *         = 0xFFDC
 *
 *   所以 RCAP2H = 0xFF，RCAP2L = 0xDC
 ************************************************************/
void UART_Init(void)
{
    /******** 第一步：配置串口控制寄存器 SCON ********/
    // SCON寄存器各位（从高位到低位）：
    // SM0 SM1 SM2 REN TB8 RB8 TI RI
    //  0   1   0   0   0   0   0  0
    // SM0=0, SM1=1 → 模式1：8位UART，波特率可变
    // SM2=0 → 非多机通信模式（单机通信）
    // REN=0 → 禁止接收（本实验只发送，可以不开启）
    // TB8/RB8 → 模式1不用，设为0
    // TI=0, RI=0 → 清除发送和接收标志
    SCON = 0x40;   // 0100 0000，模式1，禁止接收

    /******** 第二步：配置定时器2控制寄存器 T2CON ********/
    // T2CON寄存器各位（从高位到低位）：
    // TF2 EXF2 RCLK TCLK EXEN2 TR2 CT2 CPRL2
    //  0   0    1    1     0    1   0    0
    // RCLK=1 → 接收时钟使用定时器2
    // TCLK=1 → 发送时钟使用定时器2
    // TR2=1  → 启动定时器2
    // CT2=0  → 定时模式（对内部机器周期计数）
    // CPRL2=0 → 自动重装模式（波特率发生器模式）
    // TF2/EXF2 → 溢出标志和外部标志，波特率模式下不产生中断
    T2CON = 0x34;  // 0011 0100

    /******** 第三步：设置定时器2重装初值 RCAP2H/RCAP2L ********/
    // 波特率9600对应的重装值为 0xFFDC
    // RCAP2H 是高8位，RCAP2L 是低8位
    RCAP2H = 0xFF;  // 重装值高8位
    RCAP2L = 0xDC;  // 重装值低8位

    /******** 第四步：启动定时器2 ********/
    // 将TL2和TH2也设置为初值，确保第一次计数正确
    TH2 = 0xFF;
    TL2 = 0xDC;

    // TR2 = 1 启动定时器2
    // 注意：T2CON的TR2位已经在上面设置过了
    // 这里单独列出来是为了强调启动步骤
    // TR2 = 1;  // 如果T2CON没设置TR2，需要单独启动
}

/*************************** 发送单字节函数 ***************************/
/************************************************************
 * 函数名：UART_SendByte
 * 功能：通过串口发送一个字节的数据
 * 参数：dat - 要发送的字节数据（unsigned char，范围0~255）
 * 返回值：无
 *
 * 发送过程：
 *   1. 将数据写入SBUF（发送缓冲寄存器）
 *   2. 硬件自动开始发送：起始位 → 8位数据 → 停止位
 *   3. 发送完成后，硬件将TI标志位置1
 *   4. 软件检测TI=1，说明发送完成
 *   5. 软件清零TI，为下一次发送做准备
 *
 * 注意事项：
 *   - SBUF是只写的（发送时），写入后立即开始发送
 *   - TI必须由软件清零，硬件不会自动清零
 *   - 发送前最好检查TI是否为0（确保上一次发送已完成）
 ************************************************************/
void UART_SendByte(unsigned char dat)
{
    SBUF = dat;     // 将数据写入发送缓冲寄存器SBUF
                    // 写入后，硬件自动开始发送数据
                    // 发送顺序：起始位(低) → D0~D7 → 停止位(高)

    while(TI == 0); // 等待发送完成
                    // TI是发送中断标志位（SCON寄存器的第1位）
                    // 发送完一帧数据后，硬件自动将TI置1
                    // 这里循环等待，直到TI变为1

    TI = 0;         // 软件清零TI标志
                    // 注意：TI必须由软件清零
                    // 如果不清零，下一次while判断会直接通过
                    // 导致数据还没发完就被覆盖
}

/*************************** 发送字符串函数 ***************************/
/************************************************************
 * 函数名：UART_SendString
 * 功能：通过串口发送一个字符串（以'\0'结尾）
 * 参数：str - 指向字符串的指针
 * 返回值：无
 *
 * 原理：
 *   循环发送字符串中的每个字符，直到遇到字符串结束符'\0'
 *   C语言中字符串是以'\0'（ASCII码0）结尾的字符数组
 *
 * 指针说明：
 *   unsigned char *str 是一个指向unsigned char类型的指针
 *   *str 表示取指针指向的内容
 *   str++ 表示指针向后移动一个字节（指向下一个字符）
 *
 * 调用示例：
 *   UART_SendString("Hello World\r\n");
 ************************************************************/
void UART_SendString(unsigned char *str)
{
    // 循环：当*str不等于'\0'时，继续发送
    // '\0'是字符串结束标志（ASCII码为0）
    while(*str != '\0')
    {
        UART_SendByte(*str);  // 发送当前字符
        str++;                // 指针后移，指向下一个字符
    }
}

/*************************** 延时函数 ***************************/
/************************************************************
 * 函数名：Delay_ms
 * 功能：毫秒级软件延时
 * 参数：ms - 延时毫秒数
 * 说明：11.0592MHz晶振下，约等于1ms
 ************************************************************/
void Delay_ms(unsigned int ms)
{
    unsigned int i, j;
    for(i = ms; i > 0; i--)
        for(j = 921; j > 0; j--);
}

/*************************** 知识补充 ***************************
 *
 * 【串口通信基础概念】
 *
 * 1. 串行通信 vs 并行通信
 *    - 并行：多位数据同时传输，速度快但线路多、干扰大
 *    - 串行：数据一位一位依次传输，线路少、距离远
 *    - UART是最常用的串行通信方式
 *
 * 2. 波特率（Baud Rate）
 *    - 每秒传输的二进制位数，单位：bps（bit per second）
 *    - 常用波特率：9600、19200、38400、57600、115200
 *    - 通信双方波特率必须一致
 *
 * 3. 数据帧格式（模式1）
 *    起始位(1位低电平) + 数据位(8位) + 停止位(1位高电平)
 *    共10位 = 1起始 + 8数据 + 1停止
 *
 *    波形示例（发送字符'A'，ASCII 0x41 = 01000001）：
 *    ___     _   ___   ___
 *       \_/\_/ \_/   \_/
 *       S 0 1 2 3 4 5 6 7 P
 *       起始位    数据位    停止位
 *       (低)     (LSB先发) (高)
 *
 * 4. 为什么选择11.0592MHz晶振？
 *    11.0592MHz可以精确分频出标准波特率：
 *    11059200 / 12 / 32 / 9600 = 3（整数，无误差）
 *    如果用12MHz晶振，9600波特率会有误差
 *
 * 【51单片机串口工作模式】
 *
 *   模式0：移位寄存器方式（8位同步）
 *     - 8位数据，从RXD输出/输入，TXD输出移位时钟
 *     - 波特率固定：晶振频率/12
 *     - 常用于扩展IO口（74HC164、74HC165等）
 *
 *   模式1：8位UART（最常用）
 *     - 10位帧：1起始 + 8数据 + 1停止
 *     - 波特率可变，由定时器1或定时器2决定
 *     - 用于双机通信、与PC通信等
 *
 *   模式2：9位UART，波特率固定
 *     - 11位帧：1起始 + 8数据 + 1可编程位 + 1停止
 *     - 波特率 = 晶振频率 / 32 或 / 64（由SMOD决定）
 *     - 第9位可用于奇偶校验或多机通信地址帧
 *
 *   模式3：9位UART，波特率可变
 *     - 帧格式同模式2
 *     - 波特率可变，由定时器1或定时器2决定
 *     - 常用于多机通信
 *
 * 【定时器2作为波特率发生器 vs 定时器1】
 *
 *   定时器1方式（传统方式）：
 *     - 使用定时器1的模式2（8位自动重装）
 *     - 波特率 = (2^SMOD / 32) × (晶振 / 12) / (256 - TH1)
 *     - 缺点：占用了定时器1，不能再用作定时/计数
 *
 *   定时器2方式（推荐，52系列才有）：
 *     - 使用定时器2的16位自动重装模式
 *     - 波特率 = 晶振 / (32 × (65536 - RCAP2))
 *     - 优点：波特率更精确，不占用定时器1
 *     - STC89C52是52系列，推荐使用定时器2
 *
 * 【SBUF的特殊性】
 *   SBUF在物理上是两个独立的寄存器：
 *   - 写SBUF → 写入发送缓冲器，开始发送
 *   - 读SBUF → 读取接收缓冲器的数据
 *   它们共用同一个地址0x99，但通过读写操作区分
 *   这就是为什么可以同时收发（全双工）
 *
 * 【常见问题排查】
 *   1. 串口收不到数据？
 *      - 检查TXD/RXD是否接反（单片机TXD接模块RXD）
 *      - 检查波特率设置是否正确
 *      - 检查是否共地（GND必须连接）
 *      - 检查USB转TTL模块驱动是否正常
 *
 *   2. 数据乱码？
 *      - 波特率不匹配（最常见）
 *      - 晶振频率不对
 *      - 串口助手的参数设置错误
 *
 *   3. 只能发送第一个字节？
 *      - 检查TI标志是否清零
 *      - TI必须软件清零，否则后续发送会出问题
 *****************************************************************************/

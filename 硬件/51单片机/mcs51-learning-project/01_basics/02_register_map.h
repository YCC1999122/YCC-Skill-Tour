/*************************** 学习总结 ***************************
 *
 * 【51单片机特殊功能寄存器（SFR）分布】
 *
 * 地址    寄存器    可位寻址    功能
 * 0x80    P0        是          P0口
 * 0x81    SP        否          堆栈指针
 * 0x82    DPL       否          数据指针低字节
 * 0x83    DPH       否          数据指针高字节
 * 0x87    PCON      否          电源控制
 * 0x88    TCON      是          定时器控制
 * 0x89    TMOD      否          定时器模式
 * 0x8A    TL0       否          定时器0低字节
 * 0x8B    TL1       否          定时器1低字节
 * 0x8C    TH0       否          定时器0高字节
 * 0x8D    TH1       否          定时器1高字节
 * 0x90    P1        是          P1口
 * 0x98    SCON      是          串口控制
 * 0x99    SBUF      否          串口数据缓冲
 * 0xA0    P2        是          P2口
 * 0xA8    IE        是          中断允许
 * 0xB0    P3        是          P3口
 * 0xB8    IP        是          中断优先级
 * 0xC8    T2CON     是          定时器2控制（52系列）
 * 0xD0    PSW       是          程序状态字
 * 0xE0    ACC       是          累加器A
 * 0xF0    B         是          B寄存器
 *
 * 【记忆技巧】
 * 1. P0/P1/P2/P3 分别在 0x80/0x90/0xA0/0xB0（每次+0x10）
 * 2. TCON/SCON/IE/IP 分别在 0x88/0x98/0xA8/0xB8（每次+0x10）
 * 3. 能被8整除的地址都可以位寻址
 * 4. 累加器ACC在0xE0，B寄存器在0xF0
 * 5. PSW在0xD0
 *
 * 【学习建议】
 * 1. 先熟悉P0-P3口的操作
 * 2. 重点掌握TCON、TMOD、IE、SCON这几个最常用的寄存器
 * 3. 每个寄存器的功能要在实际编程中理解，不要死记硬背
 * 4. 编程时遇到问题先查寄存器定义
 *****************************************************************************/

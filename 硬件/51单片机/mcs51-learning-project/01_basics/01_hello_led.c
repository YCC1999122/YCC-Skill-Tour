/*****************************************************************************
 * 文件名：01_hello_led.c
 * 描述：51单片机入门程序 - LED闪烁实验
 * 芯片：STC89C52RC
 * 晶振：11.0592MHz
 * 编译环境：Keil uVision5 / C51
 *
 * 功能说明：
 *   控制P1.0口连接的LED灯周期性闪烁
 *   理解51单片机IO口的基本操作、sbit关键字、延时函数的原理
 *
 * 硬件连接：
 *   LED阳极（长脚）→ 220Ω限流电阻 → VCC(5V)
 *   LED阴极（短脚）→ P1.0引脚
 *   （低电平点亮，高电平熄灭）
 *
 * 学习要点：
 *   1. sbit关键字定义特殊功能寄存器的位
 *   2. 51单片机IO口的准双向结构
 *   3. 软件延时函数的原理与计算
 *   4. while(1)死循环的作用
 *****************************************************************************/

// 包含51单片机寄存器定义头文件
// 该头文件定义了所有特殊功能寄存器（SFR）的名称和地址
#include <reg52.h>

/*************************** 位定义区 ***************************/
// 使用sbit关键字定义单个IO口引脚
// sbit是C51扩展的关键字，用于访问特殊功能寄存器中的某一位
// P1是特殊功能寄存器（地址0x90），P1^0表示P1寄存器的第0位
// 这里定义LED连接在P1.0引脚上
sbit LED = P1^0;   // LED连接到P1.0引脚，sbit位定义

/*************************** 函数声明区 ***************************/
// 函数声明：告诉编译器函数的存在，以便在定义之前可以调用
void Delay_ms(unsigned int ms);  // 毫秒级延时函数声明

/*************************** 主函数 ***************************/
/************************************************************
 * 函数名：main
 * 功能：主函数，程序入口
 * 参数：无
 * 返回值：无（51单片机程序永不返回）
 * 说明：
 *   main函数是C程序的入口点
 *   51单片机上电复位后，从main函数开始执行
 *   嵌入式程序通常是一个死循环，不断重复执行
 ************************************************************/
void main(void)
{
    // 初始化：设置LED初始状态
    // 51单片机上电后，所有IO口默认为高电平（0xFF）
    // 所以LED默认是熄灭的（因为低电平点亮）
    LED = 1;    // 熄灭LED（高电平），1表示高电平

    // 主循环：嵌入式程序的核心，永远循环执行
    // while(1) 表示条件永远为真，循环永不退出
    while(1)
    {
        /******** 第一步：点亮LED ********/
        LED = 0;            // 将P1.0引脚置为低电平（0）
                            // LED阴极接低电平，阳极通过电阻接VCC
                            // 形成电流回路，LED点亮

        Delay_ms(500);      // 延时500毫秒，保持LED点亮状态
                            // 延时的目的是人眼可以看到LED的亮灭状态
                            // 如果没有延时，LED闪烁太快，人眼看不到

        /******** 第二步：熄灭LED ********/
        LED = 1;            // 将P1.0引脚置为高电平（1）
                            // LED两端电压差为0，没有电流
                            // LED熄灭

        Delay_ms(500);      // 延时500毫秒，保持LED熄灭状态
    }
    // 注意：程序永远不会执行到这里
}

/*************************** 延时函数 ***************************/
/************************************************************
 * 函数名：Delay_ms
 * 功能：软件延时函数（毫秒级）
 * 参数：ms - 延时的毫秒数（unsigned int类型，范围0~65535）
 * 返回值：无
 *
 * 原理说明：
 *   软件延时的本质是让CPU执行空操作循环，消耗时间
 *   51单片机的指令周期 = 12 / 晶振频率
 *   本程序使用11.0592MHz晶振：
 *   机器周期 = 12 / 11059200 ≈ 1.085μs
 *
 *   注意：软件延时不是精确的，因为：
 *   1. 函数调用和返回需要时间
 *   2. 循环变量的计算需要时间
 *   3. 中断会打断延时（如果开启了中断）
 *
 *   精确延时应该使用定时器（见04_timer目录）
 ************************************************************/
void Delay_ms(unsigned int ms)
{
    unsigned int i, j;  // 定义循环变量
                        // unsigned int是16位无符号整数（2字节）
                        // 取值范围：0 ~ 65535

    // 外层循环：控制延时的毫秒数
    // 每次外层循环大约延时1毫秒
    for(i = ms; i > 0; i--)
    {
        // 内层循环：实现约1毫秒的延时
        // 11.0592MHz晶振下，j从921递减到0大约需要1ms
        // 这个值需要根据实际晶振频率调整
        for(j = 921; j > 0; j--)
        {
            // 空循环体，什么都不做
            // 仅仅通过循环消耗CPU时间
            // 每次循环包含：j-- 比较和跳转，约几个机器周期
        }
    }
}

/*************************** 补充知识 ***************************
 *
 * 【关于sbit】
 * sbit有三种定义方式：
 * 1. sbit 位名 = 寄存器名^位号;    （最常用）
 *    例如：sbit LED = P1^0;
 *
 * 2. sbit 位名 = 字节地址^位号;
 *    例如：sbit LED = 0x90^0;  （P1的地址是0x90）
 *
 * 3. sbit 位名 = 位地址;
 *    例如：sbit LED = 0x90;    （P1.0的位地址是0x90）
 *
 * 【关于51单片机的IO口】
 * STC89C52有4个8位IO口：P0, P1, P2, P3
 * - P0口：开漏输出，需要外接上拉电阻才能输出高电平
 * - P1/P2/P3口：准双向口，内部有上拉电阻
 *
 * 准双向口的含义：
 *   1. 输出高电平时，可以被外部拉低作为输入
 *   2. 输出低电平时，不能被外部拉高
 *   3. 作为输入前，需要先写1（高电平）
 *
 * 【关于程序的执行流程】
 * 1. 上电复位 → PC指针指向0x0000地址
 * 2. 启动代码（C51自动添加）→ 初始化堆栈、变量等
 * 3. 调用main函数
 * 4. 进入while(1)死循环
 * 5. 永远循环执行...
 *****************************************************************************/
